import assert from "node:assert/strict";
import { createTradeFlowHistory, getGhostPacketAlpha, getPacketTrailSteps, getTradeCorridorWidth } from "../src/views/world-map/trade-corridors.js";

const h = createTradeFlowHistory({ maxEntries: 3 });
h.record(10, [{ sourceRegionId: "a", destinationRegionId: "b", amount: 5 }, { sourceRegionId: "b", destinationRegionId: "a", amount: 2 }]);
h.record(20, [{ sourceRegionId: "c", destinationRegionId: "a", amount: 4 }]);
let flows = h.netFlows(20, 30);
const ab = flows.find((f) => (f.from === "a" && f.to === "b") || (f.from === "b" && f.to === "a"));
assert.equal(ab.from, "a", "net direction follows the larger side");
assert.ok(ab.net > 0 && ab.net < ab.gross);
assert.equal(Math.max(...flows.map((f) => f.intensity)), 1);
assert.equal(h.netFlows(5, 30).length, 0, "future boundaries never leak into the past");
assert.equal(h.netFlows(20, 5).length, 1, "window drops old boundaries");
h.record(30, []); h.record(40, []);
assert.equal(h.size, 3, "history is bounded");
assert.equal(getGhostPacketAlpha(0, 10), 0.28);
assert.equal(getGhostPacketAlpha(10, 10), 0);
assert.ok(getTradeCorridorWidth(1, true) > getTradeCorridorWidth(1, false));
const trail = getPacketTrailSteps(0.9);
assert.equal(trail.length, 5);
assert.ok(Math.abs(trail[0].alpha - 0.72) < 1e-9 && trail[4].progress >= 0.49);
assert.equal(getPacketTrailSteps(0.05).length, 0);
console.log("[trade-corridors] net flow, ghost decay, trail OK");
const a = createTradeFlowHistory();
for (let s = 1; s <= 10; s++) a.record(s * 4, [{ sourceRegionId: s <= 4 ? "x" : "y", destinationRegionId: "z", amount: 1 }]);
const recent = a.netFlows(40, 1000, 3);
assert.equal(recent.length, 1, "only the last N anchors contribute");
assert.equal(recent[0].from, "y");
console.log("[trade-corridors] anchor window OK");
import { getGhostPacketAgeSec, pruneGhostPackets } from "../src/views/world-map/trade-corridors.js";
const pk = { startedSec: 100, durationSec: 1.8 };
assert.equal(getGhostPacketAgeSec(pk, 90), null, "rewind: no ghost ahead of viewed time");
assert.equal(getGhostPacketAgeSec(pk, 101), null, "still in flight is not a ghost");
assert.ok(Math.abs(getGhostPacketAgeSec(pk, 103) - 1.2) < 1e-9);
assert.deepEqual(pruneGhostPackets([pk, { startedSec: 10, durationSec: 1.8 }], 50).map((g) => g.startedSec), [10], "rewind prunes future ghosts");
const c = createTradeFlowHistory();
c.record(8, [{ sourceRegionId: "a", destinationRegionId: "b", amount: 3 }]);
assert.equal(c.netFlows(8, 100).length, 1);
c.clear();
assert.equal(c.size, 0); assert.equal(c.netFlows(8, 100).length, 0, "timeline invalidation clears corridor trend");
console.log("[trade-corridors] rewind ghosts + history clear OK");
import { ghostsFromReplacedBatch } from "../src/views/world-map/trade-corridors.js";
import { shouldInvalidateSettlementTimelineForecast as isTimelineChange } from "../src/views/ui-root/timeline-invalidation-reasons.js";
// History clears only on real timeline changes, never on ordinary browsing.
assert.equal(isTimelineChange("scrubBrowse"), false, "scrubBrowse keeps the corridor trend");
for (const r of ["init", "saveLoad", "actionDispatched", "scrubCommit", "plannerClear", "plannerCommit:x"]) assert.equal(isTimelineChange(r), true, r);
const keep = createTradeFlowHistory();
keep.record(8, [{ sourceRegionId: "a", destinationRegionId: "b", amount: 1 }]);
const onInvalidate = (reason) => { if (isTimelineChange(reason)) keep.clear(); };
onInvalidate("scrubBrowse"); assert.equal(keep.netFlows(8, 100).length, 1, "scrubBrowse does not empty trend");
onInvalidate("scrubCommit"); assert.equal(keep.size, 0, "real invalidate clears trend");
// Replaced batches: ghosts only when advancing to a later boundary.
const prev = [{ startedSec: 10, durationSec: 1.8 }];
assert.equal(ghostsFromReplacedBatch(prev, { previousBoundarySec: 10, nextBoundarySec: 14, direction: 1, viewedSec: 14 }).length, 1);
assert.equal(ghostsFromReplacedBatch(prev, { previousBoundarySec: 10, nextBoundarySec: 10, direction: 1, viewedSec: 14 }).length, 0, "same-boundary replacement (edit) cannot resurrect");
assert.equal(ghostsFromReplacedBatch(prev, { previousBoundarySec: 10, nextBoundarySec: undefined, direction: 1, viewedSec: 14 }).length, 0, "null batch drops");
assert.equal(ghostsFromReplacedBatch(prev, { previousBoundarySec: null, nextBoundarySec: 14, direction: 1, viewedSec: 14 }).length, 0, "after history clear nothing resurrects");
assert.equal(ghostsFromReplacedBatch(prev, { previousBoundarySec: 10, nextBoundarySec: 14, direction: -1, viewedSec: 14 }).length, 0, "rewind drops");
console.log("[trade-corridors] scrubBrowse keeps trend, invalidate clears, no resurrected packets OK");
