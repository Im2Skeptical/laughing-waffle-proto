import assert from 'node:assert/strict';
import {createWheelZoom} from '../images/dark-fantasy/map-generation-prototype/wheel-zoom.js';
let pose={zoom:1,x:0,y:0}, paints=0, id=0;
const queue=new Map();
const camera={snapshot:()=>({...pose}),restore:p=>{pose={...p};}};
const zoom=createWheelZoom(camera,()=>paints++,{request:fn=>{queue.set(++id,fn);return id;},cancel:id=>queue.delete(id)});
const step=t=>{const callbacks=[...queue.values()];queue.clear();callbacks.forEach(fn=>fn(t));};
zoom.wheel(-120,{x:400,y:200});
assert.equal(pose.zoom,1,'Wheel should set a target without jumping');
step(0);
assert.ok(pose.zoom>1&&pose.zoom<Math.exp(.18),'First frame must be intermediate');
assert.ok(Math.abs((400-pose.x)/pose.zoom-400)<1e-8,'Cursor anchor drift');
zoom.wheel(-120,{x:400,y:200});
for(let t=16;t<1500;t+=16)step(t);
assert.ok(Math.abs(pose.zoom-Math.exp(.36))<1e-8,'Wheel notches should accumulate');
assert.ok(paints>10,'Zoom must render intermediate frames');
zoom.wheel(120,{x:400,y:200});zoom.cancel();const stopped={...pose};step(2000);
assert.deepEqual(pose,stopped,'Pan/cancel must stop the pending wheel transition');
console.log('Wheel zoom: intermediate frames, accumulated input, cursor anchoring and cancellation pass.');
