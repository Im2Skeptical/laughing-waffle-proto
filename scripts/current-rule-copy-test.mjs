// Focused current-display checks, replacing the paused audit's stale baseline
// and source-code parser. These do not interpret the gameplay DSL or authored prose.
import assert from 'node:assert/strict';
import { detailedSettlementPracticeDefs as practices } from '../src/defs/gamepieces/detailed-settlement-defs.js';
import { VASSAL_SIGNATURE_NODE_VARIANTS } from '../src/defs/gamepieces/vassal-life-map-defs.js';
import { VASSAL_CLASS_RULES } from '../src/defs/vassal-class-rules.js';
import { createNewGameState } from '../src/model/new-game.js';
import { classActionOptions } from '../src/model/vassal-life-map/class-actions.js';

for (const id of ['alchemy', 'charnelAlchemy', 'experimentation']) {
  const def = practices[id];
  const amount = def.effects.find(effect => effect.op === 'addMonsterPressure').amount;
  assert.match(def.ui.rule, new RegExp(`(?:add|adds) ${amount} Monster (?:Pressure|expansion progress)`, 'i'),
    `${id} must disclose the pressure generated by its discharge`);
}
assert.doesNotMatch(practices.forecasting.ui.rule, /Knowledge.tagged/i);
assert.doesNotMatch(practices.mountedRaiding.ui.rule, /additional friendly connection|stronger yield from low.Defense/i);
assert.match(practices.monsterHunting.ui.rule, /Martial Force/);
assert.doesNotMatch(practices.monsterHunting.ui.rule, /sufficient Martial Support/);
assert.match(VASSAL_SIGNATURE_NODE_VARIANTS.monsterHunt.description, /Campaign.*Martial Force.*1 Edible/);
const state = createNewGameState(42);
const options = classActionOptions(state, {classId:'scholar',locationRegionId:state.civilization.capitalRegionId}, 'discovery');
assert.equal(options.length, 2);
for (const option of options) {
  assert.ok(option.label.includes(`+${option.classAction.research} Research`));
  assert.ok(option.label.includes(`+${VASSAL_CLASS_RULES.scholar.discoveryResearchPerPoint} per Ingenuity`),
    'Discovery label includes the effective-stat bonus');
}
console.log('[current-rule-copy] pressure, provider/target eligibility, Campaign and Discovery bonuses OK');
