import assert from 'node:assert/strict';
import {mkdtemp,mkdir,writeFile,rm,readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {gzipSync,gunzipSync} from 'node:zlib';
import {performanceFixtureKey,ensurePerformanceFixture} from './performance-fixture.mjs';
import {PERFORMANCE_START_SEEDS,performanceStartFixturePath,selectPerformanceStartSeed} from '../src/controllers/performance-start-seeds.js';
import {loadPerformanceStart,getPerformanceRandomSeedPreference} from '../src/controllers/performance-start.js';
import {serializeGameState} from '../src/model/state.js';
import {createNewGameState} from '../src/model/new-game.js';
import {buildProjectionChunkFromStateData} from '../src/model/projection-chunk.js';
import {createNewGameOpeningController} from '../src/controllers/new-game-opening-controller.js';
const originalStorage=Object.getOwnPropertyDescriptor(globalThis,'localStorage');
Object.defineProperty(globalThis,'localStorage',{configurable:true,value:{getItem:()=> 'on'}});
globalThis.location={search:''};
assert.equal(getPerformanceRandomSeedPreference(),true,'remembers random starts');
globalThis.location.search='?perf=1&seed=123';
assert.equal(getPerformanceRandomSeedPreference(),false,'explicit fixed link overrides the preference');
globalThis.location.search='?perf=1&seed=random';
assert.equal(getPerformanceRandomSeedPreference(),true,'direct random link');
Object.defineProperty(globalThis,'localStorage',{configurable:true,get(){throw Error('blocked');}});
globalThis.location.search='';
assert.equal(getPerformanceRandomSeedPreference(),false,'fixed seed remains the default when storage is blocked');
if(originalStorage)Object.defineProperty(globalThis,'localStorage',originalStorage);else delete globalThis.localStorage;
delete globalThis.location;
assert.equal(PERFORMANCE_START_SEEDS.length,5);
assert.equal(new Set(PERFORMANCE_START_SEEDS).size,5);
for(let roll=0;roll<50;roll++)assert.equal(selectPerformanceStartSeed({search:'?seed=prepared',randomUint32:()=>roll}),PERFORMANCE_START_SEEDS[roll%5]);
const entropy=[4294967295,4];
assert.equal(selectPerformanceStartSeed({randomUint32:()=>entropy.shift()}),PERFORMANCE_START_SEEDS[4],'out-of-range rolls are retried without modulo bias');
for(const seed of PERFORMANCE_START_SEEDS)assert.equal(selectPerformanceStartSeed({search:`?seed=${seed}`,randomUint32:()=>{throw Error('pinned seed must not roll');}}),seed);
assert.throws(()=>performanceStartFixturePath(999),/Unknown/);
const temp=await mkdtemp(path.join(tmpdir(),'perf-key-'));
try{
 for(const folder of ['src/model','src/defs','src/controllers','src/views/ui-root','scripts'])await mkdir(path.join(temp,folder),{recursive:true});
 for(const file of ['scripts/performance-fixture.mjs','scripts/performance-fixture-recipe.mjs','src/controllers/performance-start-seeds.js','package-lock.json','src/views/ui-root/settlement-timegraph-window.js','src/model/example.js','src/defs/example.js'])await writeFile(path.join(temp,file),'original');
 const first=await performanceFixtureKey(temp);
 await writeFile(path.join(temp,'src/views/ui.js'),'UI edit');assert.equal(await performanceFixtureKey(temp),first);
 await writeFile(path.join(temp,'src/model/example.js'),'rule edit');assert.notEqual(await performanceFixtureKey(temp),first);
 const changed=await performanceFixtureKey(temp);
 await writeFile(path.join(temp,'src/controllers/performance-start-seeds.js'),'new seed pool');assert.notEqual(await performanceFixtureKey(temp),changed,'changing the pool invalidates its bake');
}finally{await rm(temp,{recursive:true,force:true});}
await ensurePerformanceFixture();
const compressed=await readFile(performanceStartFixturePath(123)),payload=JSON.parse(gunzipSync(compressed));
globalThis.document={baseURI:'http://fixture/',getElementById:()=>({textContent:JSON.stringify({performanceFixtureKey:payload.key})})};
const fetcher=async()=>new Response(compressed);
for(const seed of PERFORMANCE_START_SEEDS){
 const bytes=await readFile(performanceStartFixturePath(seed));
 const requests=[];
 const prepared=await loadPerformanceStart({seed,fetcher:async url=>{requests.push(url.pathname);return new Response(bytes);}});
 assert.deepEqual(requests,[`/${performanceStartFixturePath(seed)}`],'loads only the selected world');
 assert.deepEqual(serializeGameState(prepared.state),serializeGameState(createNewGameState(seed)));
 const fresh=buildProjectionChunkFromStateData(serializeGameState(prepared.state),0,prepared.forecast.endSec);
 assert.equal(prepared.lossSec,prepared.forecast.terminal?prepared.forecast.endSec:null,'bounded survival is not labelled as extinction');
 assert.deepEqual(prepared.forecast.summaryBySecond,[...fresh.summaryBySecond]);
 assert.deepEqual(prepared.forecast.stateDataBySecond,[...fresh.stateDataBySecond]);
 assert.deepEqual(prepared.forecast.lastStateData,fresh.lastStateData);
 prepared.state.tSec=99;
 let workerCreated=false;
 const opening=createNewGameOpeningController({loadPrepared:()=>loadPerformanceStart({seed,fetcher:async()=>new Response(bytes)}),createWorkerService(){workerCreated=true;throw Error('must not simulate');}});
 const result=await opening.prepare();
 assert.equal(result.ok,true);assert.equal(workerCreated,false);
 assert.equal(result.state.tSec,0,'each entry owns an independent mutable state');
 assert.equal(result.state.rng.baseSeed,seed);opening.cancel();
 console.log(`[performance-start] seed ${seed}: exact state, summaries/anchors and no opening simulation OK`);
}
const stale=gzipSync(JSON.stringify({...payload,key:'obsolete'}));
await assert.rejects(loadPerformanceStart({seed:123,fetcher:async()=>new Response(stale)}),/stale/);
await assert.rejects(loadPerformanceStart({seed:1867,fetcher}),/seed does not match/,'a wrong-seed response cannot be installed');
console.log('[performance-start] five-seed selection, independent state, UI reuse, gameplay/pool invalidation, stale/wrong-seed rejection OK');

const switched=createNewGameOpeningController({createWorkerService(){throw Error('cancelled normal preparation must not start a worker');}});
const obsolete=switched.prepare();
switched.setPreparedLoader(()=>loadPerformanceStart({fetcher,seed:123}));
assert.equal((await obsolete).reason,'cancelled');
assert.equal((await switched.prepare()).ok,true,'menu switches an already running page to the prepared start');
switched.cancel();

let randomWorlds=0;
const randomOpening=createNewGameOpeningController({loadPrepared:()=>loadPerformanceStart({fetcher,seed:123}),
 createState:()=>{randomWorlds++;throw Error('live-random-world');}});
const oldFixed=randomOpening.prepare();
randomOpening.setPreparedLoader(null);
assert.equal((await oldFixed).reason,'cancelled','switching to random cancels the old fixed job');
assert.equal((await randomOpening.prepare()).reason,'live-random-world','random enters the live creation path');
assert.equal(randomWorlds,1);
randomOpening.setPreparedLoader(()=>loadPerformanceStart({fetcher,seed:123}));
assert.equal((await randomOpening.prepare()).state.rng.baseSeed,123,'switching back restores the baked start');
randomOpening.cancel();
