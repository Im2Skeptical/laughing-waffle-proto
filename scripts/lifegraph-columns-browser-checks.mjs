import assert from 'node:assert/strict';

export async function checkLifegraphColumns(page){
  const fill=async(label,value)=>{const field=page.getByLabel(label,{exact:true});await field.fill(value);await field.press('Tab');};
  await page.getByTestId('lifegraph-tab-columns').click();
  assert.deepEqual(await page.evaluate(()=>{const c=__LAB_DEBUG__.getLifegraph().draft.generatorConfig;return [c.laneCount,c.normalDepthCount,c.design.nodes.discovery.occurrence,c.design.guarantees.some(g=>g.targetId==='discovery')];}),[5,13,'rare',false]);
  await page.getByLabel('Preview life stage',{exact:true}).selectOption('scholar');
  await page.waitForFunction(()=>__LAB_DEBUG__.getLifegraph().graph?.nodes.find(n=>n.bookend==='founding')?.depth===4);
  await page.getByTestId('lifegraph-rule-down-founding').click();
  await page.waitForFunction(()=>!__LAB_DEBUG__.getLifegraph().graph?.foundingNodeId);
  assert.match(await page.getByTestId('lifegraph-rule-status-founding').textContent(),/Milestone 3 takes priority/);
  await page.getByTestId('lifegraph-rule-up-founding').click();
  await page.waitForFunction(()=>!!__LAB_DEBUG__.getLifegraph().graph?.foundingNodeId);
  await page.getByLabel('Preview life stage',{exact:true}).selectOption('successor');
  await page.getByTestId('lifegraph-fallback-milestone-3').click();
  await fill('Milestone milestone-2 name','Scholar alternative');
  await page.getByLabel('Scholar alternative class',{exact:true}).selectOption('scholar');
  await page.getByLabel('Scholar alternative life stage',{exact:true}).selectOption('successor');
  await page.getByLabel('Scholar alternative content',{exact:true}).selectOption('pool:growth');
  await page.getByTestId('lifegraph-rule-up-milestone-2').click();
  await page.waitForFunction(()=>__LAB_DEBUG__.getLifegraph().graph?.nodes.find(n=>n.depth===4)?.milestoneId==='milestone-2');
  await page.getByLabel('Scholar alternative enabled',{exact:true}).uncheck();
  await page.waitForFunction(()=>__LAB_DEBUG__.getLifegraph().graph?.nodes.find(n=>n.depth===4)?.family==='crossroads');
  await page.getByLabel('Scholar alternative enabled',{exact:true}).check();
  await page.getByTestId('lifegraph-class-warrior').click();
  await page.waitForFunction(()=>__LAB_DEBUG__.getLifegraph().graph?.nodes.find(n=>n.depth===4)?.family==='crossroads');
  await page.getByTestId('lifegraph-class-scholar').click();
  await page.reload();await page.getByTestId('lab-lifegraph').waitFor();
  await page.getByTestId('lifegraph-tab-columns').click();
  assert.equal(await page.getByLabel('Scholar alternative life stage',{exact:true}).inputValue(),'successor');
  assert.equal(await page.evaluate(()=>__LAB_DEBUG__.getLifegraph().graph.nodes.find(n=>n.depth===4).milestoneId),'milestone-2');
  await page.screenshot({path:'artifacts/lifegraph-rule-priority-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'rule priority and condition controls fit mobile');
  await page.screenshot({path:'artifacts/lifegraph-rule-priority-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  // Isolate the existing column/lifecycle checks from the new authored layout.
  for(const id of ['milestone-1','milestone-2','milestone-3','milestone-4'])await page.getByTestId(`lifegraph-column-${id}`).getByRole('button',{name:'Remove milestone',exact:true}).click();
  await fill('Founding depth','0');
  await page.getByTestId('lifegraph-add-column').click();
  await page.getByTestId('lifegraph-column-milestone-1').waitFor();
  await fill('Milestone milestone-1 name','Early practices');
  await page.getByLabel('Practice Reform milestones only',{exact:true}).check();
  await page.getByTestId('lifegraph-add-column').click();
  await fill('Milestone milestone-2 name','Later practices');
  await fill('Later practices depth','8');
  await page.waitForFunction(()=>__LAB_DEBUG__.getLifegraph().diagnostics?.families.practiceReform.minOnRoute===2);
  assert.equal(await page.evaluate(()=>__LAB_DEBUG__.getLifegraph().diagnostics.families.practiceReform.count),2);
  await page.getByLabel('Early practices class',{exact:true}).selectOption('scholar');
  await page.getByTestId('lifegraph-class-warrior').click();
  await page.waitForFunction(()=>__LAB_DEBUG__.getLifegraph().diagnostics?.families.practiceReform.count===1);
  await page.getByTestId('lifegraph-class-scholar').click();
  await page.waitForFunction(()=>__LAB_DEBUG__.getLifegraph().diagnostics?.families.practiceReform.count===2);
  await page.getByLabel('Legacy position',{exact:true}).selectOption('5');
  await page.waitForFunction(()=>__LAB_DEBUG__.getLifegraph().graph?.nodes.find(n=>n.bookend==='legacy')?.depth===4);
  await page.getByLabel('Preview life stage',{exact:true}).selectOption('scholar');
  await fill('Founding depth','2');
  await page.waitForFunction(()=>__LAB_DEBUG__.getLifegraph().graph?.nodes.find(n=>n.bookend==='founding')?.depth===1);
  await fill('Founding depth','7');
  await page.waitForFunction(()=>__LAB_DEBUG__.getLifegraph().graph?.nodes.find(n=>n.bookend==='founding')?.depth===6);
  await fill('Founding depth','3');
  await page.waitForFunction(()=>__LAB_DEBUG__.getLifegraph().graph?.nodes.find(n=>n.bookend==='founding')?.depth===2);
  assert.match(await page.getByTestId('lifegraph-column-milestone-1').textContent(),/Founding takes priority at this depth/);
  await page.getByLabel('Preview life stage',{exact:true}).selectOption('successor');
  await page.waitForFunction(()=>__LAB_DEBUG__.getLifegraph().graph?.nodes.some(n=>n.milestoneId==='milestone-1'));
  await page.getByLabel('Preview life stage',{exact:true}).selectOption('scholar');
  await page.waitForFunction(()=>!__LAB_DEBUG__.getLifegraph().graph?.nodes.some(n=>n.milestoneId==='milestone-1'));
  await fill('Founding depth','7');
  await page.getByTestId('lifegraph-play-founding').click();
  await page.waitForFunction(()=>__LAB_DEBUG__.getNodeSandbox()?.modal.animation.phase==='open');
  assert.equal(await page.evaluate(()=>__LAB_DEBUG__.getNodeSandbox().vassal.classId),null);
  await page.getByTestId('lifegraph-close-player').click();
  await page.getByLabel('Legacy enabled',{exact:true}).uncheck();
  await page.getByLabel('Founding enabled',{exact:true}).uncheck();
  await page.waitForFunction(()=>{const g=__LAB_DEBUG__.getLifegraph().graph;return g&&!g.bossNodeId&&!g.foundingNodeId;});
  await page.reload();await page.getByTestId('lab-lifegraph').waitFor();
  assert.equal(await page.evaluate(()=>__LAB_DEBUG__.getLifegraph().draft.generatorConfig.design.bookends.legacy.enabled),false);
  await page.getByTestId('lifegraph-tab-columns').click();
  await page.getByLabel('Founding enabled',{exact:true}).check();
  await page.getByLabel('Legacy enabled',{exact:true}).check();
  await page.getByLabel('Preview life stage',{exact:true}).selectOption('successor');
  await page.screenshot({path:'artifacts/lifegraph-milestone-controls.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'milestone controls fit the phone viewport');
  await page.screenshot({path:'artifacts/lifegraph-milestone-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.getByTestId('lifegraph-tab-graph').click();
  await page.getByLabel('Graph node',{exact:true}).selectOption('life-milestone-milestone-1');
  await page.getByTestId('lifegraph-play-selected').click();
  await page.waitForFunction(()=>__LAB_DEBUG__.getNodeSandbox()?.modal.animation.phase==='open');
  assert.equal(await page.evaluate(()=>__LAB_DEBUG__.getNodeSandbox().vassal.lifeMap.graph.nodes.find(n=>n.id===__LAB_DEBUG__.getNodeSandbox().nodeId).family),'practiceReform');
  await page.getByTestId('lifegraph-close-player').click();
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'artifacts/lifegraph-milestone-graph.png',fullPage:true});
  await page.getByTestId('lifegraph-tab-share').click();
  await page.getByRole('button',{name:'Show current export',exact:true}).click();
  const exported=JSON.parse(await page.getByLabel('Lifegraph JSON',{exact:true}).inputValue());
  assert.equal(exported.generatorConfig.design.columns.length,2);
  assert.equal(exported.generatorConfig.design.bookends.legacy.depth,5);
  await page.getByTestId('lifegraph-load-defaults').click();
}
