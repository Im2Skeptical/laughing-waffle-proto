import assert from 'node:assert/strict';
import { createOpeningController } from '../images/dark-fantasy/life-map-opening-prototype/controller.js';
import { cloneOpeningSession, openingVassal, commitOpeningEncounter } from '../images/dark-fantasy/life-map-opening-prototype/model.js';
import { getCampaignPresentation, campaignForce } from '../images/dark-fantasy/life-map-opening-prototype/campaign-experiment.js';
import { serializeGameState } from '../src/model/state.js';
const c=createOpeningController(),draft=c.getSnapshot().draft;
const state=()=>JSON.stringify(serializeGameState(c.getSnapshot().session.state));
const world=()=>JSON.stringify(c.getSnapshot().session.state.world);
c.previewCampaign();let p=c.getDecision().campaign;
assert.deepEqual(p.force,{prowess:6,retinue:4,warriors:18,arms:12,armedWarriors:12,total:22});
assert.ok(p.targets.some(target=>target.distance>1),'distant targets remain available');
assert.ok(new Set(p.targets.map(target=>target.foodCost)).size>1,'near and distant targets have different food prices');
assert.ok(p.targets.every(target=>target.foodCost===1+target.distance));
const pure=state();for(let i=0;i<5;i++)c.getDecision();assert.equal(state(),pure,'reading force/risk spends no RNG or resources');
assert.throws(()=>commitOpeningEncounter(c.getSnapshot().session),/workshop mockup/);
await assert.rejects(c.commit(),/Choose a Campaign target/);assert.equal(c.getSnapshot().canRewind,false);
c.getSnapshot().session.state.world.connections=[];
assert.deepEqual(c.getDecision().campaign.targets.map(target=>target.id),p.targets.map(target=>target.id),'targets do not require roads or adjacency');
for(const [inputs,expected] of [[{prowess:9},25],[{prestige:50},23],[{arms:18},28],[{warriors:10},20],[{arms:0},10]]) {
  c.previewCampaign(inputs);assert.equal(c.getDecision().campaign.force.total,expected);
}
c.previewCampaign();const camp=c.getSnapshot().session.campaign;
assert.equal(campaignForce(camp,true).total,6,'solo quests use Prowess only');

c.previewCampaign({prowess:10000});const baselineWorld=world(),first=c.getDecision().campaign.targets[0];
c.selectCampaignTarget(first.regionId);assert.equal(c.getDecision().campaign.selectedTargetId,first.id);
assert.equal(c.getSnapshot().session.campaign.history.length,0);assert.equal(c.getDecision().campaign.targets[0].risk,0);
const initialFood=c.getDecision().campaign.resources.food;await c.commit();
let session=c.getSnapshot().session,monster=session.campaign.monsters.find(monster=>monster.regionId===first.regionId);
assert.equal(monster.expansion,0);assert.equal(monster.cleared,true);assert.equal(monster.nest,true);
assert.equal(session.activeId,'martial');assert.equal(session.campaign.resources.food,initialFood-first.foodCost);
assert.equal(openingVassal(session).prestige,35);assert.equal(world(),baselineWorld,'clearing is a mock world outcome');
const won=structuredClone(session.campaign.history.at(-1)),wonState=state();
c.rewind();await c.commit();assert.deepEqual(c.getSnapshot().session.campaign.history.at(-1),won);assert.equal(state(),wonState,'rewind reproduces the attempt and RNG');
assert.deepEqual(cloneOpeningSession(c.getSnapshot().session).campaign,c.getSnapshot().session.campaign);
p=c.getDecision().campaign;assert.equal(p.targets.find(target=>target.id===first.id).stage,'nest');
await c.commit();assert.equal(c.getSnapshot().session.campaign.monsters.find(monster=>monster.regionId===first.regionId).nest,false);
assert.ok(!c.getDecision().campaign.targets.some(target=>target.id===first.id));assert.equal(world(),baselineWorld);
c.select('neutrals');const neutral=c.getDecision().campaign.targets[0];c.selectCampaignTarget(neutral.regionId);await c.commit();
assert.ok(c.getSnapshot().session.campaign.neutrals.find(site=>site.regionId===neutral.regionId).allied);
assert.ok(!c.getDecision().campaign.targets.some(target=>target.regionId===neutral.regionId));assert.equal(world(),baselineWorld,'alliance does not annex a normal-game site');
c.leaveCampaign();assert.equal(c.getSnapshot().session.activeId,null);assert.deepEqual(c.getSnapshot().session.availableIds,['supply']);
assert.equal(c.getSnapshot().session.outcomes.at(-1).campaign.length,3);c.rewind();assert.equal(c.getSnapshot().session.activeId,'martial');

c.previewCampaign({prowess:10000,prestige:0,arms:0,warriors:0});
assert.equal(c.getDecision().options[0].blocked,'Insufficient Prestige');c.select('quest');
const quest=c.getDecision().campaign.targets[0];assert.equal(quest.cost,0);assert.equal(quest.force,10000);
c.selectCampaignTarget(quest.regionId);await c.commit();session=c.getSnapshot().session;
assert.equal(session.campaign.history.at(-1).relic,'Monster relic');assert.equal(session.campaign.resources.prestige,10);
assert.equal(openingVassal(session).prestige,10);assert.equal(session.activeId,'martial');
assert.ok(!c.getDecision().campaign.targets.some(target=>target.id===quest.id),'a quest cannot be farmed repeatedly');
c.previewCampaign({prowess:0,prestige:0,arms:0,warriors:0});c.select('quest');
const doomed=c.getDecision().campaign.targets[0];assert.equal(doomed.risk,100);c.selectCampaignTarget(doomed.regionId);await c.commit();
assert.equal(c.getDecision().campaign.failed,true);assert.ok(c.getDecision().options.every(option=>option.blocked==='Expedition ended'));
assert.equal(openingVassal(c.getSnapshot().session).isDead,false,'defeat severity is a mock expedition end, not a new death rule');
c.leaveCampaign();assert.equal(c.getSnapshot().session.activeId,null);
c.previewCampaign({food:0});assert.ok(c.getDecision().options.every(option=>option.blocked==='Insufficient food'));
assert.deepEqual(c.getSnapshot().draft,draft);
console.log('[opening-campaign] OK: force inputs, all-range food prices, pure risk previews, staged monsters, alliance, solo relic quest, defeat, continuation, undo/RNG and draft isolation');
