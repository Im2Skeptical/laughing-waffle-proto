for(const [kind,registry] of [['practice','practices'],['structure','structures']]) {
  for(const [id,def] of Object.entries(gameConfig.gamepieces[registry])) {
    locks.flag(kind,id,def);
    locks.setLocked(kind,id,true);
  }
}
