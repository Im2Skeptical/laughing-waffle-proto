import assert from 'node:assert/strict';
globalThis.location={search:'?dev=1&perf=1'};
let uploads=0,loads=0,waiting=0;
const texture={baseTexture:{valid:true,realWidth:16,realHeight:16}};
globalThis.PIXI={SCALE_MODES:{NEAREST:0},MIPMAP_MODES:{OFF:0},Assets:{async load(){loads++;return {textures:{'fixture.png':texture},data:{}};}}};
const art=await import('../src/views/chronicle-art.js');
const file='full-map-content-prototype/art/fixture.png';
const renderer={prepare:{add(){},async upload(){uploads++;if(uploads===1)assert.equal(art.getChronicleTexture(file),null,'art stays hidden until GPU upload completes');}}};
const firstBatch=await art.loadProgressiveChronicleArt({renderer,wait:async()=>{waiting++;},onError(error){throw error;}});
assert.equal(art.getChronicleTexture(file),null);assert.equal(firstBatch.reveal(),true);
assert.ok(art.getChronicleTexture(file));assert.ok(loads>1);assert.ok(uploads<=loads);assert.ok(waiting>=uploads*2);
const before=loads;
await art.loadProgressiveChronicleArt({renderer,wait:async()=>{throw Error('already loaded groups should be reused');}});
assert.equal(loads,before);
const cancelled=await import('../src/views/chronicle-art.js?cancelled');
let current=true;
await cancelled.loadProgressiveChronicleArt({renderer,wait:async()=>{current=false;},isCurrent:()=>current});
assert.equal(loads,before,'cancelled scene starts no new asset loads');
const {loadProgressiveArtwork}=await import('../src/views/progressive-artwork.js');
let allowed=true,idleCalls=0,terrainPrepared=false,terrainRevealed=false,revealPending;
globalThis.requestIdleCallback=callback=>{idleCalls++;if(idleCalls===1){allowed=false;setTimeout(()=>{allowed=true;},0);}callback();};
await loadProgressiveArtwork({renderer,canLoad:()=>allowed,isCurrent:()=>true,
  async prepareTerrain(){assert.equal(allowed,true);assert.ok(idleCalls>=2,'menu change during idle defers the next batch');terrainPrepared=true;return ()=>{terrainRevealed=true;return true;};},onReady(reveal){revealPending=reveal;},onError(error){throw error;}});
assert.equal(terrainPrepared,true);assert.equal(terrainRevealed,false);
assert.equal(revealPending(),true);assert.equal(terrainRevealed,true);
const {getProgressiveArtworkPreference}=await import('../src/views/minimal-graphics.js');
globalThis.location.search='?perf=1';globalThis.localStorage={getItem:()=> 'off'};
assert.equal(getProgressiveArtworkPreference(),false);
globalThis.location.search='?perf=1&art=1';assert.equal(getProgressiveArtworkPreference(),true);
const staged=await import('../src/views/chronicle-art.js?staged');
const batch=await staged.loadProgressiveChronicleArt({renderer,wait:async()=>{},onError(error){throw error;}});
assert.equal(batch.ok,true);
assert.equal(staged.getArtRevision(),0,'background preparation cannot invalidate or redraw visible art');
assert.equal(staged.getChronicleTexture(file),null,'completed artwork remains hidden until the explicit reveal');
assert.equal(batch.reveal(),true);assert.ok(staged.getChronicleTexture(file));
const failing=await import('../src/views/chronicle-art.js?failing');
const originalLoad=PIXI.Assets.load;let failures=0;
PIXI.Assets.load=async url=>{if(url.includes('full-map-content'))throw Error('optional atlas unavailable');return originalLoad(url);};
const incomplete=await failing.loadProgressiveChronicleArt({renderer,wait:async()=>{},onError(){failures++;}});
assert.equal(incomplete.ok,false);assert.equal(incomplete.reveal,undefined);
assert.equal(failures,1);assert.equal(failing.getChronicleTexture('chronicle-gate-v1/fixture.png'),null,'partial success cannot leak art or offer a ready reveal');
PIXI.Assets.load=originalLoad;
console.log('[progressive-art] staged reveal, readiness/failure gating, deferred terrain, cancellation and reuse OK');
