import assert from 'node:assert/strict';
import {checkLifegraphRelicPools} from './lifegraph-relic-browser-checks.mjs';
import {checkLifegraphColumns} from './lifegraph-columns-browser-checks.mjs';

export async function checkLifegraphWorkspace(page,context,{reload=false}={}){
  const gymBefore=await page.evaluate(()=>JSON.stringify(__LAB_DEBUG__.getSnapshot().state));
  await page.getByRole('link',{name:'Lifegraph',exact:true}).click();
  await page.getByTestId('lab-lifegraph').waitFor();
  await checkLifegraphColumns(page);
  await page.getByTestId('lifegraph-class-warrior').click();
  await page.waitForFunction(()=>__LAB_DEBUG__.getLifegraph().draft.preview.classId==='warrior');
  assert.ok(await page.evaluate(()=>__LAB_DEBUG__.getLifegraph().diagnostics.families.campaign.minOnRoute>=1));
  await page.getByTestId('lifegraph-class-scholar').click();
  await page.getByTestId('lifegraph-tab-nodes').click();
  await page.getByTestId('lifegraph-node-stockShop').click();
  assert.equal(await page.getByLabel('Scholar Delve · Time base value',{exact:true}).inputValue(),'10');
  assert.equal(await page.getByLabel('Leave without a purchase · Time base value',{exact:true}).inputValue(),'5');
  assert.equal(await page.locator('[data-option-id=reroll]').count(),0);
  await page.getByLabel('Scholar Delve · Time base value',{exact:true}).fill('12');
  await page.getByLabel('Scholar Delve · Time base value',{exact:true}).press('Tab');
  await page.waitForFunction(()=>__LAB_DEBUG__.getLifegraph().draft.generatorConfig.design.shopServices.delve.time===12);
  await page.getByTestId('lifegraph-node-publicWorks').click();
  assert.equal(await page.getByLabel('Scholar Delve · Time base value',{exact:true}).inputValue(),'12');
  await page.getByLabel('Scholar Delve · Time base value',{exact:true}).fill('10');
  await page.getByLabel('Scholar Delve · Time base value',{exact:true}).press('Tab');
  await page.getByTestId('lifegraph-tab-share').click();
  await page.getByLabel('Saved Lifegraph experiment',{exact:true}).selectOption('Previous defaults');
  await page.getByRole('button',{name:'Load experiment',exact:true}).click();
  await page.waitForFunction(()=>__LAB_DEBUG__.getLifegraph().draft.generatorConfig.laneCount===6);
  await page.getByTestId('lifegraph-load-defaults').click();
  await page.waitForFunction(()=>__LAB_DEBUG__.getLifegraph().draft.generatorConfig.laneCount===3);
  await page.getByTestId('lifegraph-tab-nodes').click();
  await checkLifegraphRelicPools(page);
  await page.getByTestId('lifegraph-node-development').click();
  const choice=page.locator('[data-option-id="deepStudy"]');
  assert.equal(await page.locator('.lab-lifegraph-choice-card').count(),3);
  await choice.getByLabel('Deep Study · Death risk base value',{exact:true}).fill('20');
  await choice.getByLabel('Deep Study · Death risk base value',{exact:true}).press('Tab');
  await choice.getByLabel('Deep Study · Monster Pressure base value',{exact:true}).fill('23');
  await choice.getByLabel('Deep Study · Monster Pressure base value',{exact:true}).press('Tab');
  await page.waitForFunction(()=>__LAB_DEBUG__.getLifegraph().draft.generatorConfig.design.optionCosts.development.deepStudy.monsterPressure===23);
  assert.equal(await choice.getByLabel('Deep Study · Death risk base value',{exact:true}).inputValue(),'20');
  assert.match(await choice.locator('.lab-lifegraph-choice-preview').textContent(),/death risk.*\+23 Monster Pressure/);
  await choice.getByLabel('Deep Study · Death risk band',{exact:true}).selectOption('free');
  await page.waitForFunction(()=>__LAB_DEBUG__.getLifegraph().draft.generatorConfig.design.optionCosts.development.deepStudy.risk==='free');
  assert.doesNotMatch(await choice.locator('.lab-lifegraph-choice-preview').textContent(),/death risk|0%/);
  assert.match(await choice.locator('.lab-lifegraph-choice-preview').textContent(),/\+23 Monster Pressure/);
  await page.screenshot({path:'artifacts/lifegraph-independent-pressure.png',fullPage:true});
  await choice.getByLabel('Deep Study · Monster Pressure band',{exact:true}).selectOption('calculated');
  await choice.getByLabel('Deep Study · Time base value',{exact:true}).fill('3');
  await choice.getByLabel('Deep Study · Time base value',{exact:true}).press('Tab');
  await page.waitForFunction(()=>__LAB_DEBUG__.getLifegraph().draft.generatorConfig.design.optionCosts.development.deepStudy.time===3);
  await choice.getByLabel('Deep Study · Prestige band',{exact:true}).selectOption('fair');
  await page.getByTestId('lifegraph-tab-bands').click();
  await page.getByLabel('Prestige · fair',{exact:true}).fill('17');
  await page.getByLabel('Prestige · fair',{exact:true}).press('Tab');
  await page.waitForFunction(()=>__LAB_DEBUG__.getLifegraph().draft.generatorConfig.design.costBands.prestige.fair===17);
  await page.getByLabel('Practice Gold Prestige price',{exact:true}).fill('31');
  await page.getByLabel('Practice Gold Prestige price',{exact:true}).press('Tab');
  await page.getByTestId('lifegraph-tab-nodes').click();
  assert.equal(await choice.getByLabel('Deep Study · Prestige base value',{exact:true}).inputValue(),'17');
  assert.equal(await page.locator('[data-option-id="hardLesson"]').getByLabel('Hard Lesson · Prestige base value',{exact:true}).inputValue(),'0');
  await page.screenshot({path:'artifacts/lifegraph-choice-editor.png',fullPage:true});
  await page.getByTestId('lifegraph-node-practiceReform').click();
  await page.getByLabel('Node review notes').fill('Browser check: Timber has one supplier; add another choice.');
  await page.getByTestId('lifegraph-save-note').click();
  await page.getByText('Generation settings',{exact:true}).click();
  await page.getByLabel('Node family',{exact:true}).selectOption('growth');
  await page.waitForFunction(()=>__LAB_DEBUG__.getLifegraph().draft.generatorConfig.design.nodes.practiceReform.poolId==='growth');
  await page.getByLabel('Node family',{exact:true}).selectOption('shops');
  await page.getByLabel('Enabled',{exact:true}).uncheck();
  await page.waitForFunction(()=>!__LAB_DEBUG__.getLifegraph().graph.nodes.some(n=>n.family==='practiceReform'));
  await page.getByTestId('lifegraph-play-type').click();
  const canvas=page.getByTestId('lab-node-sandbox');
  await page.waitForFunction(()=>__LAB_DEBUG__.getNodeSandbox()?.modal.animation.phase==='open');
  async function point(kind,index=0){
    await canvas.scrollIntoViewIfNeeded();
    const p=await page.evaluate(({kind,index})=>__LAB_DEBUG__.getNodeSandboxPoint(kind,index),{kind,index});assert.ok(p,`${kind} point exists`);
    const r=await canvas.boundingBox();return {x:r.x+p.x*r.width/2424,y:r.y+p.y*r.height/1080};
  }
  async function click(kind,index=0){const p=await point(kind,index);await page.mouse.move(p.x,p.y);await page.waitForTimeout(180);const settled=await point(kind,index);await page.mouse.click(settled.x,settled.y);}
  async function chooseRandom(){
    const index=await page.evaluate(()=>__LAB_DEBUG__.getNodeSandbox().modal.shopTagChoices.findIndex(c=>c.id==='random'));
    if(index>=0){await click('tag',index);await page.waitForFunction(()=>__LAB_DEBUG__.getNodeSandbox().modal.shopTagChoices.length===0);}
  }
  await chooseRandom();
  const offers=await page.evaluate(()=>__LAB_DEBUG__.getNodeSandbox().modal.offers.map(o=>o.label));assert.ok(offers.length>0);
  await click('offer');
  if(await page.evaluate(()=>!!__LAB_DEBUG__.getNodeSandbox().modal.replacementOfferId)){const p=await point('tableau',4);await page.mouse.click(p.x,p.y);}
  await page.waitForFunction(()=>__LAB_DEBUG__.getNodeSandbox().modal.purchaseOrder.length===1);
  await click('undo');await page.waitForFunction(()=>__LAB_DEBUG__.getNodeSandbox().modal.purchaseOrder.length===0);
  await click('face');await page.waitForFunction(()=>!!__LAB_DEBUG__.getNodeSandbox().modal.inspectedCardId);
  await click('inspectClose');
  await page.getByTestId('lifegraph-reset-node').click();await page.waitForFunction(()=>__LAB_DEBUG__.getNodeSandbox().modal.animation.phase==='open');await chooseRandom();
  assert.deepEqual(await page.evaluate(()=>__LAB_DEBUG__.getNodeSandbox().modal.offers.map(o=>o.label)),offers,'reset reproduces the same offers');
  await page.screenshot({path:'artifacts/lifegraph-player-desktop.png'});
  await page.getByTestId('lifegraph-close-player').click();await page.getByLabel('Enabled',{exact:true}).check();
  await page.getByTestId('lifegraph-tab-diagnostics').click();
  await page.getByTestId('lifegraph-run-batch').click();
  await page.waitForFunction(()=>__LAB_DEBUG__.getLifegraph().batch?.completed===100);
  assert.equal(await page.evaluate(()=>__LAB_DEBUG__.getLifegraph().batch.failed),0);
  assert.equal(await page.evaluate(()=>__LAB_DEBUG__.getLifegraph().cardPools.find(p=>p.id==='stock:Timber').count),1);
  await page.getByTestId('lifegraph-tab-share').click();
  await page.getByRole('button',{name:'Show current export',exact:true}).click();
  const exported=await page.getByLabel('Lifegraph JSON',{exact:true}).inputValue();
  const doc=JSON.parse(exported);assert.equal(doc.reviews.practiceReform.status,'open');assert.equal(doc.evidence.batch.completed,100);
  assert.equal(doc.generatorConfig.design.optionCosts.development.deepStudy.time,3);
  assert.equal(doc.generatorConfig.design.shopPricing.prices.practice.gold.prestige,31);
  await page.getByTestId('lifegraph-save-preset').click();
  if(reload){await page.reload();await page.getByTestId('lab-lifegraph').waitFor();}
  assert.ok(await page.evaluate(()=>__LAB_DEBUG__.getLifegraph().draft.reviews.practiceReform.notes.includes('Timber')));
  assert.equal(await page.evaluate(()=>__LAB_DEBUG__.getLifegraph().draft.generatorConfig.design.optionCosts.development.deepStudy.time),3);
  await page.getByTestId('lifegraph-tab-share').click();
  await page.getByLabel('Lifegraph JSON',{exact:true}).fill(exported);await page.getByTestId('lifegraph-import-json').click();
  await page.getByTestId('lifegraph-tab-graph').click();
  await page.screenshot({path:'artifacts/lifegraph-desktop.png',fullPage:true});
  assert.ok(await page.evaluate(()=>JSON.stringify(__LAB_DEBUG__.getSnapshot().state))===gymBefore,'Lifegraph does not change Gym state');
  await page.getByRole('link',{name:'Gym',exact:true}).click();
  await page.getByTestId('lab-workspace-setup').click();
  await page.getByTestId('debug-profile-copy').click();
  await page.getByTestId('debug-lifeMapLab-tab').click();
  await page.getByTestId('lab-setup-lifegraph').click();
  await page.getByText('Pooled generation',{exact:true}).waitFor();
  await page.getByRole('link',{name:'Lifegraph',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  await page.getByTestId('lifegraph-tab-nodes').click();
  await page.getByTestId('lifegraph-node-stockShop').click();
  await page.getByLabel('Practice Gold Prestige price',{exact:true}).waitFor();
  await page.screenshot({path:'artifacts/lifegraph-mobile.png',fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'mobile tools fit the viewport');
  await page.getByTestId('lifegraph-play-type').click();await page.locator('dialog[open]').waitFor();
  await page.getByTestId('lifegraph-close-player').click();
  await page.setViewportSize({width:1280,height:800});
  await page.getByTestId('lifegraph-class-warrior').click();
  await page.getByTestId('lifegraph-play-type').click();
  await page.waitForFunction(()=>__LAB_DEBUG__.getNodeSandbox()?.modal.animation.phase==='open');
  await page.screenshot({path:'artifacts/lifegraph-warrior-shop.png'});
  await page.getByTestId('lifegraph-close-player').click();
  await page.getByRole('link',{name:'Gym',exact:true}).click();
  await page.getByTestId('lab-workspace-settlement').click();
}
