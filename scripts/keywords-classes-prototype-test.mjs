import assert from 'node:assert/strict';
import { createKeywordPrototypeState as create } from '../src/model/keywords-classes-prototype-fixture.js';
import { keywordPrototypeScore as score, keywordScaledAmount as bonus, keywordPrototypeAccess as access } from '../src/model/keywords-classes-prototype.js';
import { advanceReplayStateToSecond as advance, initializeReplayClock } from '../src/model/replay-second-runner.js';
import { createTimelineFromInitialState, rebuildStateAtSecond } from '../src/model/timeline/index.js';
import { serializeGameState, deserializeGameState } from '../src/model/state.js';
import { getDetailedPracticeDef } from '../src/model/game-config.js';
import { getDetailedSettlementSites } from '../src/model/detailed-settlements/queries.js';
import { emitPracticeEvent } from '../src/model/detailed-settlements/practice-events.js';
import { getVassalCandidatePool, selectLifeMapVassal } from '../src/model/vassal-life-map.js';
import { stockOutputBreakdown, stockCapacity } from '../src/model/detailed-settlements/stock.js';
import { evaluateDetailedPracticeSlot } from '../src/model/detailed-settlements/practices.js';
import { getGamepieceFace } from '../src/model/gamepiece-presentation.js';
import { synthesisContributors } from '../src/model/detailed-settlements/synthesis.js';

for(const mode of ['disciplines','lenses','teachings'])for(const classId of ['scholar','warrior','priest','merchant']) {
  const state=create(mode,classId),home=state.civilization.capitalRegionId;
  initializeReplayClock(state);
  const timeline=createTimelineFromInitialState(state);
  const count=score(state,home,'economicRegions');
  assert.equal(count,3,'two allies and a connected neutral form one trade zone');
  const disconnected=deserializeGameState(serializeGameState(state));
  disconnected.world.connections=[];
  assert.equal(score(disconnected,home,'economicRegions'),1,'disconnecting roads breaks zones');
  const a=access(state,'economicRegions'),b=access(state,'monsterTrophies');
  assert.equal(a.active,mode!=='disciplines'||classId==='merchant');
  assert.equal(b.active,mode==='lenses'||(mode==='teachings'?['warrior','scholar']:['warrior','priest']).includes(classId));
  assert.equal(advance(state,12).ok,true);
  assert.equal(score(state,home,'monsterTrophies'),mode==='disciplines'&&classId==='scholar'?0:1,'a real Hunt kills and records one monster');
  const scale={keyword:'monsterTrophies',per:1,amount:1,cap:6};
  assert.equal(bonus(state,home,scale),b.active?1:0);
  const rebuilt=rebuildStateAtSecond(timeline,12);
  assert.equal(rebuilt.ok,true);
  assert.deepEqual(serializeGameState(rebuilt.state),serializeGameState(state),'authoritative replay equals live state including RNG');
  const resumed=deserializeGameState(JSON.parse(JSON.stringify(serializeGameState(state))));
  assert.equal(advance(resumed,18).ok,true);assert.equal(advance(state,18).ok,true);
  assert.deepEqual(serializeGameState(resumed),serializeGameState(state),'JSON resume preserves rules, history, and RNG');
  if(mode==='lenses') {
    const def=getDetailedPracticeDef(state,['scholar','merchant'].includes(classId)?'barter':'observation');
    assert.equal(def.effects.length,2,'class lens adds another DSL effect');
    if(classId==='warrior')assert.ok(getDetailedSettlementSites(state,{playerOnly:true}).some(s=>s.detailedState.supportBank?.formation>0),'trophies actually bank Support');
  }
}
const taught=create('teachings','warrior');
assert.equal(access(taught,'economicRegions').active,true,'a Warrior inherits the earlier economic teaching');
const untaught=create('teachings','warrior',{inherited:false});
assert.equal(access(untaught,'economicRegions').active,false,'no teacher means no economic bonus');
untaught.civilization.vassalLineage.selectedVassalIds=['teacher'];
untaught.civilization.vassalLineage.vassalsById.teacher={classId:'merchant',isDead:true};
assert.equal(access(untaught,'economicRegions').active,true,'a dead teacher still passes the discipline on');
const initial=score(untaught,untaught.civilization.capitalRegionId,'monsterTrophies');
emitPracticeEvent(untaught,{kind:'defenseSucceeded'});
emitPracticeEvent(untaught,{kind:'campaignWon'});
assert.equal(score(untaught,null,'monsterTrophies'),initial,'defenses and neutral conquests are not monster kills');
emitPracticeEvent(untaught,{kind:'monsterDestroyed'});
assert.equal(score(untaught,null,'monsterTrophies'),initial+1);
const selected=create('disciplines','scholar');
const warrior={...getVassalCandidatePool(selected).candidates[1],founderClassId:null,classId:'warrior'};
assert.equal(selectLifeMapVassal(selected,1,null,warrior).ok,true);
assert.equal(access(selected,'economicRegions').active,false,'actual selected class takes over from launch role');
assert.equal(access(selected,'monsterTrophies').active,true);
selected.civilization.vassalLineage.currentVassalId=null;
assert.equal(access(selected,'monsterTrophies').active,false,'exclusive bonuses become dormant between lives');
selected.gameConfig.keywordPrototype.mode='teachings';
assert.equal(access(selected,'monsterTrophies').active,true,'the recorded teacher still grants an inherited bonus between lives');
const multiplied=create('disciplines','merchant');
const home=getDetailedSettlementSites(multiplied,{playerOnly:true})[0],barter=home.detailedState.practiceSlots[1];
const originalCapacity=stockCapacity(multiplied,home.detailedState,barter);
assert.equal(getDetailedPracticeDef(multiplied,'barter').effects[0].amount,1,'keyword does not edit base output');
assert.equal(getDetailedPracticeDef(multiplied,'observation').prototypeKeyword,undefined,'Research is not treated as Stock output');
const pool=stockOutputBreakdown(multiplied,home.detailedState,barter);
assert.equal(pool.multiplier,4,'base one plus three Economic Regions');
assert.deepEqual(pool.sources.map(({label,amount})=>({label,amount})),[{label:'Economic Regions',amount:3}]);
assert.equal(stockOutputBreakdown(multiplied,home.detailedState,barter,false,[{kind:'outputMultiplier',amount:2,sourceId:'other',sourceLabel:'Other source',query:{}}]).multiplier,6,'keyword adds into the existing pool');
const withoutKeyword=deserializeGameState(serializeGameState(multiplied));
delete withoutKeyword.gameConfig.keywordPrototype;
assert.equal(originalCapacity,stockCapacity(withoutKeyword,withoutKeyword.world.sites.find(s=>s.regionId===home.regionId).detailedState,barter),'Capacity Multiplier is untouched');
multiplied.gameConfig.gamepieces.practices.barter.effects[0].amount=2;
multiplied.gameConfig.gamepieces.practices.barter.workerCapacity=0;
multiplied.gameConfig.gamepieces.practices.barter.workerBonus=0;
multiplied.gameConfig.gamepieces.practices.barter.stockCapacity=100;
barter.stock=0;
assert.equal(advance(multiplied,1).ok,true);
assert.equal(barter.stock,8,'real activation produces base 2 × Output Multiplier 4, not base 2 + 3');
const martial=create('disciplines','warrior'),martialSite=getDetailedSettlementSites(martial,{playerOnly:true})[0];
martial.civilization.history.monsterTrophies=2;
const huntSlot=martialSite.detailedState.practiceSlots[3],huntDef=getDetailedPracticeDef(martial,'monsterHunting');
assert.equal(stockOutputBreakdown(martial,martialSite.detailedState,huntSlot).multiplier,3);
const hunting=evaluateDetailedPracticeSlot(martial,martialSite.regionId,3);
assert.equal(hunting.effects[0].scaledValue.effectiveValue,3*3*hunting.effects[0].scaledValue.workerMultiplier,'Trophies multiply the original three-Stock yield');
assert.equal(hunting.effects[1].scaledValue.effectiveValue,6,'Research output is unchanged');
const face=getGamepieceFace(martial,'practice','monsterHunting',huntSlot.tier,{slot:huntSlot,settlement:martialSite.detailedState});
assert.equal(face.reading.keyword.inMultiplierPool,true,'inspection routes the keyword to the existing multiplier');
assert.ok(face.reading.effects.filter(effect=>effect.timing).every(effect=>!effect.text.includes('Output Multiplier')),'timed effects do not include the passive modifier');
assert.deepEqual(face.reading.effects.at(-1),{timing:'',passive:true,text:'Monster Trophies contributes to Output Multiplier.'},'passive effect has its own untimed row');
assert.deepEqual(face.baseStockProduction.map(row=>row.amount),[huntDef.effects[0].amount]);
const synthesis=create('disciplines','scholar'),synthesisHome=synthesis.civilization.capitalRegionId;
const synthesisSite=getDetailedSettlementSites(synthesis,{playerOnly:true})[0],copying=synthesisSite.detailedState.practiceSlots[1];
assert.equal(access(synthesis,'economicRegions').active,false,'Economic Regions is Merchant-only in A');
assert.equal(access(synthesis,'synthesis').active,true,'Scholar owns Synthesis');
assert.equal(access(create('disciplines','merchant'),'synthesis').active,false,'Merchant does not gain Synthesis');
const untouched=serializeGameState(synthesis);
assert.deepEqual(synthesisContributors(synthesis,synthesisHome,'copyingTexts').map(source=>source.practiceId),['irrigating','scholarship','papermaking']);
assert.equal(score(synthesis,synthesisHome,'synthesis','copyingTexts'),3,'three other supplied Scholar-staffed Practices');
assert.equal(score(synthesis,synthesisHome,'synthesis'),4,'the host would qualify if not explicitly excluded');
const synthesisPool=stockOutputBreakdown(synthesis,synthesisSite.detailedState,copying);
assert.equal(synthesisPool.multiplier,4);
assert.deepEqual(synthesisPool.sources.map(source=>source.label),['Irrigating','Scholarship','Papermaking'],'ledger preserves contributor identities');
assert.deepEqual(serializeGameState(synthesis),untouched,'reading Synthesis does not consume, reserve or alter state/RNG');
const missingRecord=deserializeGameState(untouched);
for(const site of getDetailedSettlementSites(missingRecord,{playerOnly:true}))site.detailedState.practiceSlots[1].stock=0;
assert.equal(score(missingRecord,synthesisHome,'synthesis','copyingTexts'),2,'missing Consume inputs exclude Scholarship');
const missingWater=deserializeGameState(untouched);
for(const site of getDetailedSettlementSites(missingWater,{playerOnly:true}))site.detailedState.practiceSlots[0].stock=0;
assert.equal(score(missingWater,synthesisHome,'synthesis','copyingTexts'),2,'missing Require inputs exclude Papermaking');
getDetailedSettlementSites(missingWater,{playerOnly:true})[1].detailedState.practiceSlots[0].stock=2;
assert.equal(score(missingWater,synthesisHome,'synthesis','copyingTexts'),3,'normal allied supply can satisfy the local contributor');
const unstaffed=deserializeGameState(untouched);
const unstaffedSettlement=unstaffed.world.sites.find(site=>site.regionId===synthesisHome).detailedState;
for(const cohort of Object.values(unstaffedSettlement.populationByClass))cohort.specialists.scholar.adults=0;
assert.equal(score(unstaffed,synthesisHome,'synthesis','copyingTexts'),0,'ordinary workers never substitute for Scholar staffing');
const blocked=create('disciplines','scholar',{synthesisSupply:'blocked'});
initializeReplayClock(blocked);const blockedTimeline=createTimelineFromInitialState(blocked);
assert.equal(score(blocked,synthesisHome,'synthesis','copyingTexts'),2);
assert.equal(advance(blocked,12).ok,true);
assert.equal(score(blocked,synthesisHome,'synthesis','copyingTexts'),3,'real seasonal irrigation restores the missing Require supply');
assert.deepEqual(serializeGameState(rebuildStateAtSecond(blockedTimeline,12).state),serializeGameState(blocked),'supply recovery and Synthesis replay exactly');
const synthesisEvaluation=evaluateDetailedPracticeSlot(synthesis,synthesisHome,1);
const dormantSynthesis=deserializeGameState(untouched);
dormantSynthesis.gameConfig.keywordPrototype.classId='merchant';
const dormantEvaluation=evaluateDetailedPracticeSlot(dormantSynthesis,synthesisHome,1);
assert.equal(synthesisEvaluation.chargeGain,dormantEvaluation.chargeGain,'Synthesis does not multiply Charge gain');
assert.equal(synthesisEvaluation.stockCapacity,dormantEvaluation.stockCapacity,'Synthesis does not alter Capacity');
assert.equal(synthesisEvaluation.effects[0].scaledValue.baseValue,3);
assert.equal(synthesisEvaluation.effects[0].scaledValue.effectiveValue,12,'Synthesis uses Output Multiplier, not base output or Charge gain');
assert.equal(advance(synthesis,1).ok,true);
assert.equal(copying.stock,8,'a real Paper production event Discharges Copying Texts to its unchanged capacity');
assert.ok(synthesisSite.detailedState.practiceActivationTrace.some(entry=>entry.kind==='discharged'&&entry.targetPracticeId==='copyingTexts'));
console.log('[keywords-prototype] OK: 12 mode/class combinations, real Hunt, connected components, class effects, inherited teaching, JSON and authoritative replay');
