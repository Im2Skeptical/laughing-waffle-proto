import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdirSync,writeFileSync} from 'node:fs';
import {setTimeout as delay} from 'node:timers/promises';
import {chromium} from 'playwright';
import {BROWSER_PROBE_LAUNCH_OPTIONS} from './browser-probe-config.mjs';
const port=18889,url=`http://127.0.0.1:${port}`,artifact='artifacts/development-lab-browser-probe.json';
mkdirSync('artifacts',{recursive:true});
const server=spawn(process.execPath,['node_modules/serve/bin/serve.js','-l',String(port),'--no-clipboard','dist'],{stdio:'ignore',windowsHide:true});
let browser,page;const checks=[],errors=[];
try {
  for(let i=0;i<100;i++){try{if((await fetch(url)).ok)break;}catch{}await delay(100);}
  browser=await chromium.launch(BROWSER_PROBE_LAUNCH_OPTIONS);
  const context=await browser.newContext({viewport:{width:1280,height:800}});
  context.on('page',p=>p.on('pageerror',e=>errors.push(e.message)));
  page=await context.newPage();
  await page.goto(`${url}/#/dev/zoo`);
  await page.getByRole('heading',{name:'Development Lab',exact:true}).waitFor();
  await page.getByLabel('Search runtime content').fill('smelting');
  await page.getByText('1 matching runtime entries',{exact:false}).waitFor();
  await page.getByRole('button',{name:'Inspect / compare',exact:true}).click();
  await page.getByRole('heading',{name:'Smelting',exact:true}).waitFor();
  await page.getByLabel('Class',{exact:true}).selectOption('warrior');
  await page.getByText('0 matching runtime entries',{exact:false}).waitFor();
  await page.getByLabel('Class',{exact:true}).selectOption('');
  await page.getByLabel('Search runtime content').fill('');
  await page.getByLabel('Category',{exact:true}).selectOption('structure');
  await page.getByLabel('Slot size',{exact:true}).selectOption('3');
  await delay(1200);
  await page.screenshot({path:'artifacts/development-lab-zoo.png'});
  checks.push('runtime search, class/footprint filters, real cards, quality comparison');
  await page.getByRole('link',{name:'Museum · systems'}).click();
  await page.getByLabel('Fixture',{exact:true}).selectOption('food-31');
  await page.getByTestId('lab-load-fixture').click();
  await page.getByTestId('lab-step').click();
  await page.getByText('Meal demand\n2',{exact:true}).waitFor();
  await page.getByTestId('lab-reset').click();
  await page.getByText('t=1s',{exact:true}).waitFor();
  await page.getByTestId('lab-compare').click();
  await page.getByRole('heading',{name:'Exact projection match',exact:true}).waitFor();
  await page.getByTestId('lab-to-gym').click();
  await page.getByRole('button',{name:'Play from here'}).waitFor();
  await page.getByLabel('Adult population',{exact:true}).fill('30');
  await page.getByLabel('Warrior adults',{exact:true}).fill('30');
  await page.getByRole('button',{name:'Set adult cohort',exact:true}).click();
  await page.getByText('Warriors\n30 (was 0)',{exact:true}).waitFor();
  await page.getByLabel('Stock slot 1',{exact:true}).fill('999');
  await page.getByRole('button',{name:'Apply slot',exact:true}).first().click();
  await page.getByTestId('lab-status').filter({hasText:'at most'}).waitFor();
  await page.getByText('Reproduce and share · saved fixtures / JSON',{exact:true}).click();
  await page.getByLabel('Fixture name',{exact:true}).fill('browser reproduction');
  await page.getByRole('button',{name:'Save fixture',exact:true}).click();
  await page.getByTestId('lab-step').click();
  await page.getByTestId('lab-reset').click();
  await page.getByText('t=1s',{exact:true}).waitFor();
  checks.push('Food breakpoint, deterministic reset, forecast parity, Museum to Gym, population edit, invalid Stock rejection, saved fixture');
  await page.screenshot({path:'artifacts/development-lab-gym-desktop.png'});
  await page.getByTestId('lab-tableau').scrollIntoViewIfNeeded();
  await page.screenshot({path:'artifacts/development-lab-tableau.png'});
  await page.setViewportSize({width:844,height:390});
  await page.screenshot({path:'artifacts/development-lab-gym-mobile.png'});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true,'no page-level horizontal overflow');
  await page.setViewportSize({width:1280,height:800});
  await page.evaluate(()=>localStorage.setItem('civsurvivor.save.slot1','sentinel-original-save'));
  const playPromise=context.waitForEvent('page');
  await page.getByTestId('lab-play').click();
  const play=await playPromise;
  await play.getByTestId('lab-play-badge').waitFor({timeout:60000});
  await play.waitForFunction(()=>globalThis.__SETTLEMENT_DEBUG__);
  assert.equal(await play.evaluate(()=>__SETTLEMENT_DEBUG__.getSnapshot().frontierSec),1);
  await play.screenshot({path:'artifacts/development-lab-play-normal.png'});
  assert.equal(await play.evaluate(()=>localStorage.getItem('civsurvivor.save.slot1')),'sentinel-original-save');
  await play.keyboard.press('Control+Shift+D');
  await play.getByTestId('development-lab-clone').waitFor();
  const clonePromise=context.waitForEvent('page');
  await play.getByTestId('development-lab-clone').click();
  const clone=await clonePromise;
  await clone.getByTestId('lab-play').waitFor({timeout:60000});
  assert.equal(await clone.evaluate(()=>{
    const token=new URLSearchParams(location.hash.split('?')[1]).get('state');
    const state=JSON.parse(localStorage.getItem('civsurvivor.development-lab.handoff.'+token));
    return state.tSec;
  }),1);
  assert.ok(await clone.getByText('Warriors\n30',{exact:true}).count());
  await clone.reload();
  await clone.getByTestId('lab-play').waitFor();
  assert.ok(await clone.getByText('Warriors\n30',{exact:true}).count());
  await play.screenshot({path:'artifacts/development-lab-play.png'});
  checks.push('snapshot at t=1 launches normal game, live run clones into Gym, handoff refresh works, original save slot untouched');
  assert.deepEqual(errors,[]);
  writeFileSync(artifact,JSON.stringify({ok:true,checks},null,2));
  console.log('[probe:development-lab] OK: catalogue, exhibits, sandbox, desktop/mobile and both bridges');
} catch(e) {
  await page?.screenshot({path:'artifacts/development-lab-failure.png'}).catch(()=>{});
  writeFileSync(artifact,JSON.stringify({error:e.stack,errors,checks},null,2));
  console.error(`[probe:development-lab] FAILED: ${e.message.split('\n')[0]}; ${artifact}`);process.exitCode=1;
} finally {await browser?.close();server.kill();}
