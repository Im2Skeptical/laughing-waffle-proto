import assert from 'node:assert/strict';
import {mkdirSync,writeFileSync} from 'node:fs';
import {chromium} from 'playwright';
import {BROWSER_PROBE_LAUNCH_OPTIONS} from './browser-probe-config.mjs';
const url=new URL(process.argv[2]??'http://localhost:5184/');url.search='?dev=1';url.hash='';
const output='artifacts/region-map-style';mkdirSync(output,{recursive:true});
const browser=await chromium.launch(BROWSER_PROBE_LAUNCH_OPTIONS);
let page,checks;const errors=[];
try {
  page=await browser.newPage({viewport:{width:1280,height:570}});
  page.on('pageerror',error=>errors.push(error.message));
  await page.route(url.href,route=>route.fulfill({contentType:'text/html',body:'<html><body style="margin:0;background:#091212"><script src="https://cdn.jsdelivr.net/npm/pixi.js@7.2.4/dist/pixi.min.js"></script></body></html>'}));
  await page.goto(url.href);await page.waitForFunction(()=>!!globalThis.PIXI);
  checks=await page.evaluate(async()=>{
    const {createNewGameState}=await import('/src/model/new-game.js');
    const {serializeGameState,deserializeGameState}=await import('/src/model/state.js');
    const {getWorldDefinition}=await import('/src/model/world-state.js');
    const {createWorldMapView}=await import('/src/views/world-map-pixi.js');
    const {getRegionTerrainStyle,getRegionNameColour}=await import('/src/views/world-map/region-style.js');
    const {preloadChronicleArt}=await import('/src/views/chronicle-art.js');
    await preloadChronicleArt();
    let state=createNewGameState(123);
    const initial=serializeGameState(state),before=JSON.stringify(initial),definition=getWorldDefinition(state);
    const app=new PIXI.Application({width:1280,height:570,backgroundColor:0x091212,antialias:true});
    document.body.append(app.view);app.stage.scale.set(1280/2424);
    const view=createWorldMapView({layer:app.stage,getState:()=>state,getSelectedRegionId:()=>state.civilization.capitalRegionId,getRegionSelectionActive:()=>false});
    view.init();
    const walk=node=>[node,...(node.children??[]).flatMap(walk)];
    const labels=()=>walk(app.stage).filter(node=>node.label==='region-name');
    const label=id=>labels().find(node=>node.mapRegionId===id);
    const ink=node=>typeof node?.style.fill==='string'?parseInt(node.style.fill.replace('#',''),16):node?.style.fill;
    const fills=walk(app.stage).filter(node=>node.label==='region-biome-fill');
    const incorrectFills=definition.regions.filter(def=>fills.find(node=>node.parent.mapRegionId===def.id)?.geometry.graphicsData[0].fillStyle.color!==getRegionTerrainStyle(def.biome,state.world.regions.find(r=>r.id===def.id).colour).fill).map(r=>r.id);
    const incorrectLabels=state.world.regions.filter(region=>ink(label(region.id))!==getRegionNameColour(region)).map(r=>r.id);
    const inherited=definition.regions.filter(r=>r.biome==='mountains'&&r.initialState.colour==='red');
    const target=state.world.regions.find(r=>r.id===inherited[0].id);
    const initialUnchanged=JSON.stringify(serializeGameState(state))===before;
    const original=label(target.id),originalFill=original.style.fill;view.update();const retained=label(target.id)===original;
    target.controller='player';view.update();const captured=ink(label(target.id))===getRegionNameColour(target);
    target.monster=structuredClone(state.world.regions.find(r=>r.monster).monster);view.update();
    const occupied=ink(label(target.id))===getRegionNameColour(target);
    state=deserializeGameState(initial);view.update();
    const rewound=label(target.id).style.fill===originalFill;
    globalThis.styleProbe={app,view};
    return {incorrectFills,incorrectLabels,inherited:inherited.length,retained,captured,occupied,rewound,initialUnchanged,unchanged:JSON.stringify(serializeGameState(state))===before,nameColours:[...new Set(labels().map(node=>node.style.fill))]};
  });
  assert.deepEqual(checks.incorrectFills,[],'actual polygon fills follow natural biome');
  assert.deepEqual(checks.incorrectLabels,[],'actual text colours follow control');
  assert.equal(checks.inherited,2,'fixture covers both red-mechanics mountain regions');
  assert.equal(checks.nameColours.length,4,'all four control colours appear');
  for(const key of ['retained','captured','occupied','rewound','initialUnchanged','unchanged'])assert.equal(checks[key],true,key);
  await page.screenshot({path:`${output}/desktop.png`});
  await page.setViewportSize({width:844,height:390});
  await page.evaluate(()=>{styleProbe.app.renderer.resize(844,390);styleProbe.app.stage.scale.set(844/2424);styleProbe.app.renderer.render(styleProbe.app.stage);});
  await page.screenshot({path:`${output}/phone.png`});
  assert.deepEqual(errors,[]);
  writeFileSync(`${output}/result.json`,JSON.stringify({checks,errors},null,2));
  console.log('[region-map-style] biome fills, four control name colours, retention, capture, occupation and restored state passed');
}catch(error){
  await page?.screenshot({path:`${output}/failure.png`}).catch(()=>{});
  writeFileSync(`${output}/result.json`,JSON.stringify({error:error.stack,checks,errors},null,2));
  console.error(`[region-map-style] ${error.message}; details=${output}/result.json`);process.exitCode=1;
}finally{await browser.close();}
