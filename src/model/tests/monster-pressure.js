import assert from 'node:assert/strict';
import { createNewGameState } from '../new-game.js';
import { serializeGameState, deserializeGameState } from '../state.js';
import { getMonsterPressureRate, stepSpatialPressure, adjacentRegionIds } from '../detailed-settlements/external-world.js';
import { getActionChaosCost } from '../detailed-settlements/practice-events.js';
import { runPracticeActivation } from '../detailed-settlements/practices.js';
import { getGamepieceFace } from '../gamepiece-presentation.js';
import { getRegionState } from '../world-state.js';
import { createLabNodeSandbox } from '../dev-lab/node-sandbox.js';
import { confirmVassalLifeNode, selectVassalNodeOption } from '../vassal-life-map.js';
import { getCurrentLifeMapVassal } from '../vassal-life-map.js';
import { classActionOptions, applyClassAction } from '../vassal-life-map/class-actions.js';
import { trainSpecialists } from '../detailed-settlements/stock.js';
import { practiceSlot } from '../dev-lab/fixtures.js';

const state=createNewGameState(420), chaos=state.civilization.chaos;
const initialRng={...state.rng}, first=state.world.regions.find(region=>region.monster);
const rates=[0,100,1000,10000].map(value=>{
  chaos.chaosPower=value;return getMonsterPressureRate(state);
});
assert.ok(rates.every((rate,index)=>index===0||rate>rates[index-1]));
assert.ok(rates[3]<rates[2]*2,'tenfold Chaos has a diminishing proportional effect');
chaos.chaosPower=0;
for(let moon=0;moon<23;moon++)stepSpatialPressure(state);
assert.equal(first.monster.ageMoons,0,'the opening threat gives time to prepare');
stepSpatialPressure(state);
assert.equal(first.monster.ageMoons,1);
assert.equal(chaos.pressurePulses,1);
assert.equal(chaos.spatialSpawns,1);
const saved=serializeGameState(state), restored=deserializeGameState(saved);
for(let moon=0;moon<48;moon++){stepSpatialPressure(state);stepSpatialPressure(restored);}
assert.deepEqual(serializeGameState(state),serializeGameState(restored),'fractional pressure resumes exactly');
assert.equal(state.world.regions.filter(region=>region.monster).length,2);
assert.equal(chaos.spatialSpawns,1,'the third pulse expands an existing front instead of spawning');
assert.deepEqual(state.rng,initialRng,'pressure never consumes RNG');
assert.equal(state.tSec,0,'direct pressure stepping never advances simulation time');

const high=createNewGameState(421);high.civilization.chaos.chaosPower=1000;
for(let moon=0;moon<24;moon++)stepSpatialPressure(high);
assert.ok(high.civilization.chaos.pressurePulses>1);
assert.equal(high.civilization.chaos.chaosPower,1000,'pulses never spend or reset Chaos');
const multi=createNewGameState(424);
const multiRng={...multi.rng};
const multiFront=multi.world.regions.find(region=>region.monster);
const multiPulses=multi.civilization.chaos.pressurePulses;
multi.civilization.chaos.chaosPower=1e18;
multi.civilization.chaos.monsterPressure=.99;
assert.deepEqual(serializeGameState(deserializeGameState(serializeGameState(multi))),serializeGameState(multi),'banked pressure round-trips before the step');
stepSpatialPressure(multi);
assert.equal(multi.civilization.chaos.pressurePulses-multiPulses,2,'one step drains every whole pressure point');
assert.ok(multi.civilization.chaos.monsterPressure>=.56&&multi.civilization.chaos.monsterPressure<=.57,'two pulses leave a saved fraction between 0.56 and 0.57');
assert.equal(multiFront.monster.ageMoons,2,'two pulses advance the opening front without expanding it');
assert.equal(multi.world.regions.filter(region=>region.monster).length,1);
assert.equal(multi.civilization.chaos.spatialSpawns,1);
assert.equal(multi.civilization.chaos.chaosPower,1e18,'a multi-pulse step does not spend Chaos');
assert.deepEqual(multi.rng,multiRng,'a multi-pulse step does not consume RNG');
assert.deepEqual(serializeGameState(deserializeGameState(serializeGameState(multi))),serializeGameState(multi),'two pulses and the saved fraction round-trip');
const empty=createNewGameState(422);
for(const region of empty.world.regions)delete region.monster;
empty.civilization.chaos.monsterPressure=.999;
stepSpatialPressure(empty);
assert.equal(empty.world.regions.filter(region=>region.monster).length,1,'no existing front permits a replacement spawn');
const blocked=createNewGameState(423);
for(const region of blocked.world.regions)region.monster={defense:3,ageMoons:0};
blocked.civilization.chaos.monsterPressure=.999;
stepSpatialPressure(blocked);
assert.equal(blocked.world.regions.filter(region=>region.monster.defense===4).length,1,'fully blocked threats strengthen once per pulse');

const costs=createNewGameState(53), home=costs.world.sites.find(site=>site.regionId===costs.civilization.capitalRegionId);
home.detailedState.practiceSlots=[practiceSlot('forage',3),practiceSlot('bowmaking',3),practiceSlot('raidingParties'),null,null];
home.detailedState.populationByClass.villager.adults=30;trainSpecialists(home.detailedState,'warrior',30);
costs.currentSeasonIndex=1;
const face=getGamepieceFace(costs,'practice','raidingParties');
assert.equal(face.chaosCost,1);
assert.equal(face.inputs.find(input=>input.icon==='chaos').amount,1);
const before=costs.civilization.chaos.chaosPower;
runPracticeActivation(costs,'season');
assert.equal(costs.civilization.chaos.chaosPower-before,face.chaosCost,'Raid cost is fixed despite staffing');
home.detailedState.practiceSlots[0].stock=0;home.detailedState.practiceSlots[1].stock=0;
const after=costs.civilization.chaos.chaosPower;
runPracticeActivation(costs,'season');
assert.equal(costs.civilization.chaos.chaosPower,after,'blocked Raid pays no cost');

const scholar=createLabNodeSandbox({type:'discovery',classId:'scholar'});
const vassal=getCurrentLifeMapVassal(scholar.state), options=vassal.lifeMap.nodeStates[scholar.nodeId].options;
assert.equal(getActionChaosCost(options[0]),0);
assert.equal(getActionChaosCost(options[1]),40);
assert.equal(selectVassalNodeOption(scholar.state,scholar.nodeId,options[1].id).ok,true);
assert.equal(scholar.state.civilization.chaos.chaosPower,0,'selection is only a preview');
assert.equal(confirmVassalLifeNode(scholar.state,scholar.nodeId).ok,true);
assert.equal(scholar.state.civilization.chaos.chaosPower,40,'confirmation pays forbidden Discovery exactly once, including failed searches');
assert.equal(confirmVassalLifeNode(scholar.state,scholar.nodeId).ok,false);
assert.equal(scholar.state.civilization.chaos.chaosPower,40);

const warrior={classId:'warrior',locationRegionId:home.regionId,stats:{intelligence:20},prestige:30};
home.detailedState.practiceSlots[0].stock=3;
const conquer=classActionOptions(costs,warrior,'campaign').find(option=>getActionChaosCost(option)>0);
assert.ok(conquer,'conquest advertises its Chaos cost');
const huntId=adjacentRegionIds(costs,home.regionId).find(id=>getRegionState(costs,id).controller!=='player');
costs.world.sites=costs.world.sites.filter(site=>site.regionId!==huntId);
getRegionState(costs,huntId).controller='frontier';
assert.ok(huntId);
getRegionState(costs,huntId).monster={defense:2,ageMoons:2};
const hunt=classActionOptions(costs,warrior,'campaign').find(option=>option.classAction.targetId===huntId);
assert.equal(getActionChaosCost(hunt),0,'defensive hunting is free of Chaos');
assert.equal(hunt.prestigeDelta,20);
const research=costs.civilization.research.total;
applyClassAction(costs,warrior,hunt.classAction);
assert.equal(costs.civilization.research.total-research,6);
assert.equal(getRegionState(costs,huntId).monster,undefined);

home.detailedState.practiceSlots=[practiceSlot('forage',3),practiceSlot('bowmaking',3),practiceSlot('monsterHunting'),null,null];
getRegionState(costs,huntId).monster={defense:2,ageMoons:0};
const autoResearch=costs.civilization.research.total;
runPracticeActivation(costs,'death');
assert.equal(getRegionState(costs,huntId).monster,undefined);
assert.equal(costs.civilization.research.total-autoResearch,6);
assert.ok(home.detailedState.practiceSlots[2].stock>=5,'trophy yield grows with target Defense');
assert.ok(getGamepieceFace(costs,'practice','monsterHunting').stockTraits.includes('Currency'));
const invalid=structuredClone(saved);delete invalid.civilization.chaos.monsterPressure;
assert.throws(()=>deserializeGameState(invalid),/Monster Pressure/);
console.log('[monster-pressure] opening, curve, pulse priority, costs, rewards and saved fractional pressure OK');
