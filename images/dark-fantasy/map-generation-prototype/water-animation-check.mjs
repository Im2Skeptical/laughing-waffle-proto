import assert from 'node:assert/strict';
import { createMapTimeline } from './map-timeline.js';
import { waterPaletteColour } from './water-style.js';
const clock=createMapTimeline({currentSec:0});
assert.equal(clock.step(0),false);
assert.equal(clock.step(20),false);
assert.equal(clock.step(40),true);assert.equal(clock.snapshot.displaySec,.04);
clock.play(false);clock.step(80);clock.play();clock.step(10000);
assert.equal(clock.snapshot.displaySec,.04,'Pause must not accumulate hidden time');
clock.step(10040);assert.equal(clock.snapshot.displaySec,.08);
clock.step(20000);assert.equal(clock.snapshot.displaySec,.18,'Long bake/background stalls must not cause catch-up');
clock.seek(2.5);clock.step(21000);assert.equal(clock.snapshot.displaySec,2.5);
assert.throws(()=>clock.seek(NaN));
assert.equal(clock.snapshot.currentSec,.18,'Seeking does not commit the viewed time');
assert.equal(clock.snapshot.mode,'Forecast preview');
assert.deepEqual(clock.snapshot.sample,{tSec:2,fraction:.5,seconds:2.5});
clock.setRate(-1);clock.play();clock.step(22000);clock.step(22040);
assert.equal(clock.snapshot.displaySec,2.46);assert.equal(clock.snapshot.currentSec,.18);
clock.seek(-5);assert.equal(clock.snapshot.displaySec,0);
clock.play();clock.step(23000);clock.step(23040);assert.equal(clock.snapshot.playing,false,'Reverse stops at the start');
clock.seek(999);assert.equal(clock.snapshot.displaySec,clock.snapshot.revealCapSec);
clock.setRate(4);clock.play();clock.step(24000);clock.step(24040);
assert.equal(clock.snapshot.playing,false,'Playback stops at revealed coverage');
clock.returnToNow();assert.equal(clock.snapshot.displaySec,.18);assert.equal(clock.snapshot.followingNow,true);
clock.play();clock.step(25000);clock.step(25040);assert.ok(Math.abs(clock.snapshot.currentSec-.34)<1e-12);
clock.beginScrub();clock.seek(.125);clock.step(26000);
assert.equal(clock.snapshot.scrubbing,true);assert.equal(clock.snapshot.playing,false);
clock.endScrub();assert.equal(clock.snapshot.displaySec,.125,'Release holds the selected frame');
const palette=Array.from({length:256},(_,n)=>n),mix=(a,b,t)=>a+(b-a)*t;
assert.equal(waterPaletteColour(128,palette,mix,.1),128.3,'Subframe phase must blend smoothly');
assert.equal(waterPaletteColour(70,palette,mix,3.7),70,'Depth stays fixed');
assert.equal(waterPaletteColour(128,palette,mix,-.1),137.3,'Reverse phase wraps inside its own ramp');
const phase=waterPaletteColour(128,palette,mix,clock.snapshot.displaySec);
clock.seek(50);clock.seek(.125);
assert.equal(waterPaletteColour(128,palette,mix,clock.snapshot.displaySec),phase,'Return to time restores identical colour');
console.log('Water timeline: forward/reverse, pause, scrub, reveal cap, read-only preview, Now, fractional/reversible palette sampling pass.');
