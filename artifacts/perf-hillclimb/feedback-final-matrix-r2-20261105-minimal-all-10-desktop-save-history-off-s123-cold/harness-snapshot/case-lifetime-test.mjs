import assert from 'node:assert/strict';
import {createCaseLifetime} from './case-lifetime.mjs';

const success=createCaseLifetime({timeoutMs:1000,label:'success'});
assert.equal(await success.wait(()=>42,{label:'simple result'}),42);success.complete();success.dispose();
assert.equal(success.snapshot().status,'completed');
let started=false;
await assert.rejects(success.wait(()=>{started=true;}),/already completed/);assert.equal(started,false);
const original=new Error('original synchronous failure'),failed=createCaseLifetime({timeoutMs:1000});
await assert.rejects(failed.wait(()=>{throw original;}),error=>error===original);
assert.equal(failed.snapshot().reason,original.message);failed.dispose();
const cancelled=createCaseLifetime({timeoutMs:1000,label:'cancelled'});
let resolveLate;
const waiting=cancelled.wait(()=>new Promise(resolve=>{resolveLate=resolve;}),{label:'unconfirmed native work'});
await Promise.resolve();cancelled.cancel(new Error('explicit cancellation'));
await assert.rejects(waiting,/explicit cancellation/);
assert.equal(cancelled.snapshot().unconfirmedWork.length,1,'rejected wait does not pretend the underlying work completed');
await assert.rejects(cancelled.wait(()=>{started=true;}),/explicit cancellation/);assert.equal(started,false);
resolveLate();assert.equal((await cancelled.drain(100)).unconfirmedWork.length,0);cancelled.dispose();
const stage=createCaseLifetime({timeoutMs:1000,label:'stage'});
await assert.rejects(stage.wait(()=>new Promise(()=>{}),{timeoutMs:20,label:'never stage'}),/never stage timeout/);
assert.equal(stage.snapshot().status,'cancelled');assert.equal(stage.snapshot().unconfirmedWork.length,1);stage.dispose();
const whole=createCaseLifetime({timeoutMs:20,label:'whole case'});
await assert.rejects(whole.wait(()=>new Promise(()=>{})),/whole case lifetime timeout/);whole.dispose();
const beforeStart=createCaseLifetime({timeoutMs:1000});beforeStart.cancel(new Error('stop before start'));
await assert.rejects(beforeStart.wait(()=>{started=true;}),/stop before start/);assert.equal(started,false);beforeStart.dispose();
assert.throws(()=>createCaseLifetime({timeoutMs:Infinity}),/supported/);
assert.throws(()=>createCaseLifetime({timeoutMs:2147483648}),/supported/);
console.log('[case-lifetime] completion, original-error identity, no work after cancellation, explicit late work, stage/case deadlines and timer-range controls PASS');
