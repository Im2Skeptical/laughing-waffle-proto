function parameters(name, reading, names) {
  const source = reading ? mirrorName(name) : runtimeName(name);
  return [
    (reading ? "Import" : "const Export") + "&" + (names ? " codec" : ""),
    "const " + source + "&" + (names ? " source" : ""),
    ...(reading ? ["const std::string&" + (names ? " path" : "")] : []),
    ...(indexedRecords.has(name) ? ["std::uint32_t" + (names ? " row" : "")] : []),
  ].join(", ");
}

function readField({ key, member, type, policy, payload }) {
  const path = 'property_path(path, "' + key + '")';
  const value = "source." + member;
  if (policy === "config") return [];
  if (splitColumns.has(policy)) {
    const { column, type: columnType } = splitColumns.get(policy);
    return ["    codec." + column + "(row) = codec.read<" + columnType + ">(" + value + ", " + path + ");"];
  }
  const custom = {
    region_def: "region",
    region_ref: "region",
    site_def: "site",
    practice_board: "practices",
    structure_board: "structures",
  }[policy];
  const target = payload ? "codec.eventPayload(row)" : "result";
  return ["    " + target + "." + member + " = codec." + (custom ?? "read<" + type + ">") + "(" + value + ", " + path + ");"];
}

function writeField({ member, policy, payload }, record) {
  if (record === "MigrationMovement" && member === "transferId")
    return ["    codec.migration_transfer_id(result.transferId, source);"];
  if (policy === "config") return ["    result." + member + " = codec.state.content->config;"];
  const custom = { practice_board: "practices", structure_board: "structures" }[policy];
  const value = splitColumns.has(policy) ? "codec." + splitColumns.get(policy).column + "(row)"
    : (payload ? "codec.eventPayload(row)" : "source") + "." + member;
  return ["    codec." + (custom ?? "write") + "(result." + member + ", " + value + ");"];
}

function digestField({ member, policy, payload }, record) {
  if (record === "MigrationMovement" && member === "transferId")
    return '    codec.migration_transfer_id(source);';
  if (policy === "config") return '    codec.fields("' + member + '", codec.state.content->configHash);';
  const value = splitColumns.has(policy) ? "codec." + splitColumns.get(policy).column + "(row)"
    : (payload ? "codec.eventPayload(row)" : "source") + "." + member;
  return '    codec.fields("' + member + '", ' + value + ');';
}

const mapping = [
  banner,
  ...[...records.keys()].flatMap(name => [
    "template<> struct Mapping<" + runtimeName(name) + "> {",
    "    static " + runtimeName(name) + " read(" + parameters(name, true, false) + ");",
    "    static " + mirrorName(name) + " write(" + parameters(name, false, false) + ");",
    "    static void digest(" + parameters(name, false, false).replace("const Export&", "Digest&") + ");",
    "};", "",
  ]),
  ...[...records].flatMap(([name, fields]) => [
    runtimeName(name) + " Mapping<" + runtimeName(name) + ">::read(" + parameters(name, true, true) + ")",
    "{",
    "    " + runtimeName(name) + " result{};",
    ...fields.flatMap(readField),
    "    return result;", "}", "",
    mirrorName(name) + " Mapping<" + runtimeName(name) + ">::write(" + parameters(name, false, true) + ")",
    "{",
    "    " + mirrorName(name) + " result{};",
    ...fields.flatMap(field => writeField(field, name)),
    "    return result;", "}", "",
    "void Mapping<" + runtimeName(name) + ">::digest(" + parameters(name, false, true).replace("const Export&", "Digest&") + ")",
    "{",
    ...fields.map(field => digestField(field, name)),
    "}", "",
  ]),
].join("\n");

// Only the diagnostics tool needs to walk retained mirror values. Generate
// this walker from the schema so its byte counts cover new descendants too.
const coldMirrorRecords = new Set();
function collectColdMirrorRecords(ref) {
  const shape = schema.types[ref];
  if (shape?.kind === "record" && !coldMirrorRecords.has(ref)) {
    coldMirrorRecords.add(ref);
    for (const field of Object.values(shape.fields)) collectColdMirrorRecords(field.type);
  }
  if (shape?.kind === "array") collectColdMirrorRecords(shape.items);
  if (shape?.kind === "tuple") shape.items.forEach(collectColdMirrorRecords);
  if (shape?.kind === "dict" || shape?.kind === "nullable") collectColdMirrorRecords(shape.value);
  if (shape?.kind === "union" || shape?.kind === "oneOf") Object.values(shape.variants).forEach(collectColdMirrorRecords);
}
for (const { ref } of coldPools.values()) collectColdMirrorRecords(ref);
const mirrorFields = [
  banner,
  ...[...coldMirrorRecords].flatMap(name => [
    "void mirror_fields(const browser::" + name + "& record, auto visit)",
    "{",
    ...Object.keys(schema.types[name].fields).map(key => "    visit(record." + identifier(key) + ");"),
    "}", "",
  ]),
].join("\n");

if (process.argv.slice(2).some(arg => arg !== "--check")) {
  throw Error("Usage: node native/schema/runtime-codegen.mjs [--check]");
}
for (const [name, expected] of [
  ["rows.generated.hpp", header], ["mapping.generated.inc", mapping], ["mirror_fields.generated.inc", mirrorFields],
]) {
  const file = new URL(name, stateDir);
  if (process.argv.includes("--check")) {
    if (readFileSync(file, "utf8").replaceAll("\r\n", "\n") !== expected) {
      throw Error(name + " is stale. Run node native/schema/runtime-codegen.mjs.");
    }
  } else {
    writeFileSync(file, expected);
  }
}
