import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { identifier } from "./cpp-identifiers.mjs";

const stateDir = new URL("../src/sim/state/", import.meta.url);
const schemaDir = new URL("./", import.meta.url);
const schemaFile = readdirSync(schemaDir).filter(name => /^gamestate\.v\d+\.json$/u.test(name))
  .sort((a, b) => Number(b.split(".")[1].slice(1)) - Number(a.split(".")[1].slice(1)))[0];
const schema = JSON.parse(readFileSync(new URL(schemaFile, schemaDir), "utf8"));
const banner = "// Generated by native/schema/runtime-codegen.mjs. Do not edit.\n";

function readCoverage() {
  const coverage = new Map();
  let fields;
  for (const line of readFileSync(new URL("field-coverage.txt", stateDir), "utf8").split(/\r?\n/u)) {
    const text = line.trim();
    if (!text || text.startsWith("#")) continue;
    if (text.startsWith("[") && text.endsWith("]")) {
      const type = text.slice(1, -1);
      if (coverage.has(type)) throw Error("Duplicate record " + type);
      coverage.set(type, fields = new Map());
      continue;
    }
    const [policy, ...names] = text.split(/\s+/u);
    if (!fields || !names.length) throw Error("Expected policy and fields: " + text);
    for (const name of names) {
      if (fields.has(name)) throw Error("Duplicate field " + name);
      fields.set(name, policy);
    }
  }
  return coverage;
}

const coverage = readCoverage();
const records = new Map();
const hotPools = new Set(["Index<StructureCell>"]);
const coldPools = new Map();
const historyPools = new Map();
const historyPayloadPools = new Set();
const scalars = { boolean: "bool", number: "double", integer: "double", string: "std::string", json: "core::json::Value" };
const splitColumns = new Map([
  ["stock", { type: "std::optional<double>", column: "practiceStock" }],
  ["charge", { type: "double", column: "practiceCharge" }],
  ["joint_count", { type: "std::uint64_t", column: "jointCounts" }],
]);
// These types have columns supplied by the caller's row index.
const indexedRecords = new Set(["PracticeSlot", "JointCohort", "PracticeEvent"]);
const runtimeName = name => ({ GameState: "HotState", RngSeeds: "core::RngState" })[name] ?? name;
const mirrorName = name => scalars[name] ?? "browser::" + name;
const isId = policy => /^[A-Z][A-Za-z]*Id$/u.test(policy);

function range(element) {
  hotPools.add(element);
  return "Range<" + element + ">";
}

function wrap(field, type) {
  if (field.optional && field.nullable) return "browser::OptionalNullable<" + type + ">";
  return field.optional || field.nullable ? "std::optional<" + type + ">" : type;
}

function hotType(ref, policy = "hot") {
  if (ref === "string" && isId(policy)) return policy;
  if (ref === "integer" && policy === "u32") return "std::uint32_t";
  if (ref === "integer" && (policy === "u64" || policy === "joint_count")) return "std::uint64_t";
  if (Object.hasOwn(scalars, ref) && ref !== "string" && ref !== "json" && policy === "hot") return scalars[ref];
  const shape = schema.types[ref];
  switch (shape?.kind) {
    case "enum":
      if (policy === "hot") return mirrorName(ref);
      break;
    case "record":
      if (policy === "hot" || policy === "indexed") {
        addRecord(ref);
        const name = runtimeName(ref);
        if (policy === "hot") return name;
        hotPools.add(name);
        return "Index<" + name + ">";
      }
      break;
    case "array":
      return range(hotType(shape.items, policy));
    case "dict": {
      const [key, ...rest] = policy.split("/");
      if (isId(key)) return range("Entry<" + key + ", " + hotType(shape.value, rest.join("/") || "hot") + ">");
      break;
    }
    case "nullable":
      return "std::optional<" + hotType(shape.value, policy) + ">";
  }
  throw Error("Unsupported hot policy " + policy + " for schema type " + ref);
}

function fieldType(field, policy, owner, key) {
  if (policy === "cold") {
    const type = mirrorName(field.type);
    const tag = owner + "_" + key;
    coldPools.set(tag, { type, ref: field.type });
    return wrap(field, "ColdRef<" + type + ", " + tag + ">");
  }
  if (policy === "history" || policy.startsWith("history:")) {
    const shape = schema.types[field.type];
    if (shape.kind !== "array") throw Error("Expected a history array for " + owner + "." + key);
    const option = policy.split(":")[1] ?? "0";
    const limit = isId(option) ? "0" : option;
    if (!/^\d+$/u.test(limit)) throw Error("Invalid history limit for " + owner + "." + key);
    const row = hotType(shape.items, isId(option) ? option : "hot");
    const tag = owner + "_" + key;
    historyPools.set(tag, { row, limit });
    return wrap(field, "HistoryRef<" + row + ", " + limit + ", " + tag + ">");
  }
  if (policy === "history_range" || policy.startsWith("history_range:")) {
    const shape = schema.types[field.type];
    if (shape.kind !== "array") throw Error("Expected a history payload array for " + owner + "." + key);
    const element = hotType(shape.items, policy.split(":")[1] ?? "hot");
    historyPayloadPools.add(element);
    return wrap(field, "Range<" + element + ">");
  }
  if (policy === "config") return null;
  if (policy === "practice_board" || policy === "structure_board") {
    const shape = schema.types[field.type];
    const practice = policy === "practice_board";
    const row = practice ? "PracticeSlot" : "StructureCell";
    const items = practice ? shape.items : [shape.items];
    if (shape.kind !== (practice ? "tuple" : "array") ||
        (practice && items.length !== 5) ||
        items.some(item => schema.types[item]?.kind !== "nullable" || schema.types[item].value !== row)) {
      throw Error("Unexpected board shape for " + field.type);
    }
    addRecord(row);
    hotPools.add(row);
    return practice ? "PracticeBoard" : "StructureBoard";
  }
  if (splitColumns.has(policy)) {
    return null;
  }
  if (policy === "region_def" || policy === "region_ref") return "RegionId";
  if (policy === "site_def") return "SiteId";
  return wrap(field, hotType(field.type, policy === "joint" ? "hot" : policy));
}

function addRecord(name) {
  if (records.has(name)) return;
  const shape = schema.types[name];
  const policies = coverage.get(name);
  if (!policies) throw Error("Missing coverage for " + name);
  const fields = Object.entries(shape.fields).map(([key, field]) => {
    const placement = policies.get(key);
    if (!placement) throw Error("Unaccounted schema field " + name + "." + key);
    const payload = placement.startsWith("payload:");
    if (payload && name !== "PracticeEvent") throw Error("Unexpected payload field " + name + "." + key);
    const policy = payload ? placement.slice("payload:".length) : placement;
    return { key, member: identifier(key), type: fieldType(field, policy, name, key), policy, payload };
  });
  for (const field of policies.keys()) {
    if (!Object.hasOwn(shape.fields, field)) throw Error("Stale coverage entry " + name + "." + field);
  }
  records.set(name, fields);
}

addRecord(schema.root);
for (const name of coverage.keys()) {
  if (!records.has(name)) throw Error("Unreachable coverage entry " + name);
}

function declaration(name, fields) {
  if (name === "RngSeeds") return [];
  const columns = fields.filter(field => field.type && !field.payload);
  const payload = fields.filter(field => field.payload).map(field => ({ ...field, payload: false }));
  const extras = {
    PracticeSlot: ["    std::uint32_t slot{}, version{};"],
    StructureCell: ["    std::uint32_t version{};"],
    MigrationMovement: ["    double transferSecond{};", "    std::uint32_t transferOrdinal{};"],
  }[name] ?? [];
  return [
    "struct " + runtimeName(name) + " {",
    ...columns.map(({ type, member }) => "    " + type + " " + member + "{};"),
    ...extras,
    "};", "",
    ...(payload.length ? declaration("PracticeEventPayload", payload) : []),
  ];
}

