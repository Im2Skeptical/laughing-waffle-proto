import { readFileSync, writeFileSync } from 'node:fs';
import { VASSAL_HEIRLOOM_DEFS } from '../../src/defs/gamepieces/vassal-heirloom-defs.js';
import { VASSAL_SIGNATURE_NODE_VARIANTS } from '../../src/defs/gamepieces/vassal-life-map-defs.js';
import { FULL_MAP_SEED_CARD_IDS, isFullMapOfferDefinition } from '../../src/defs/gamepieces/full-map-defs.js';
import { detailedSettlementPracticeDefs, settlementStructureDefs } from '../../src/defs/gamepieces/detailed-settlement-defs.js';

const q = value => JSON.stringify(value);
const array = (type, name, rows) => [
  `inline constexpr ${type} ${name}[] = {`,
  ...rows.map(row => `    {${row.map(q).join(', ')}},`),
  '};',
].join('\n');

const heirlooms = array('HeirloomDef', 'heirloomDefs', Object.values(VASSAL_HEIRLOOM_DEFS).map(def => [
  def.id, def.label, def.quality,
  ...['patronageNodePrestige', 'nodeDevelopment', 'crossroadsNodeDevelopment',
    'bonusCunning', 'wisdomDevelopmentMultiplier', 'extraShopOffers',
    'mandateOfHeaven'].map(key => def.effects?.[key] ?? (key === 'mandateOfHeaven' ? false : 0)),
]));
const signatures = array('SignatureDef', 'signatureDefs', Object.values(VASSAL_SIGNATURE_NODE_VARIANTS).map(def => [
  def.id, def.groupId, def.label, def.glyph, def.color, def.description, def.removalKind ?? '', def.tag ?? '',
]));
const fullMapOffers = array('std::string_view', 'fullMapOfferIds',
  [...Object.values(detailedSettlementPracticeDefs), ...Object.values(settlementStructureDefs)]
    .filter(isFullMapOfferDefinition).map(def => [def.id]));
const seedCards = array('std::string_view', 'fullMapSeedCardIds', FULL_MAP_SEED_CARD_IDS.map(id => [id]));
const output = '// Generated by native/reference/export-vassal-tables.mjs.\n\n'
  + [heirlooms, signatures, fullMapOffers, seedCards].join('\n\n') + '\n';
const file = new URL('../src/sim/vassal/tables.inc', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(file, 'utf8').replace(/\r\n/g, '\n') !== output)
    throw new Error('Run node native/reference/export-vassal-tables.mjs to refresh Vassal tables.');
} else {
  writeFileSync(file, output);
}
